#[test]
fn u09_command_palette_focused_search_types_live_then_accepts_the_current_candidate_id() {
    let _guard = crate::tests::editor_event::support::env_lock()
        .lock()
        .unwrap();
    let mut bridge =
        BuiltinWorkbenchWindowTemplateSurfaceBridge::new(UiSize::new(1280.0, 800.0)).unwrap();
    bridge
        .open_command_palette_with_chrome(
            authored_prompt_state("", false),
            "asset-name-prompt",
            "Folder name",
            "Enter a name",
            "New Folder",
            "Create a folder",
        )
        .unwrap();
    let ui = UiHostWindow::new().unwrap();
    ui.set_host_presentation(HostWindowPresentationData {
        workbench_window_nodes: to_host_contract_workbench_window_nodes(Some(
            bridge.host_projection(),
        )),
        ..Default::default()
    });
    let edits = Rc::new(RefCell::new(Vec::new()));
    let captured = edits.clone();
    ui.global::<PaneSurfaceHostContext>()
        .on_surface_control_edited(move |control, action, value| {
            captured.borrow_mut().push((control, action, value));
        });
    focus_native_search(&ui);
    let query = "关卡 Names";
    ui.dispatch_native_key_for_test(
        key_event(Key::Character(query.into()), Some(query)),
        ModifiersState::empty(),
    );
    assert_eq!(edits.borrow().len(), 1);
    assert_eq!(edits.borrow()[0].0.as_str(), "WorkbenchCommandPalette");
    assert_eq!(edits.borrow()[0].1.as_str(), "CommandPalette/QueryChanged");
    assert_eq!(edits.borrow()[0].2.as_str(), query);
    assert_eq!(
        ui.global::<UiHostContext>()
            .get_text_input_focus()
            .value_text
            .as_str(),
        query
    );

    // Publish the candidate generated by the live query before accepting it.
    bridge
        .update_command_palette_query(authored_prompt_state(query, true))
        .unwrap();
    ui.set_host_presentation(HostWindowPresentationData {
        workbench_window_nodes: to_host_contract_workbench_window_nodes(Some(
            bridge.host_projection(),
        )),
        ..Default::default()
    });
    ui.dispatch_native_key_for_test(
        key_event(Key::Named(NamedKey::Enter), Some("\r")),
        ModifiersState::empty(),
    );
    assert_eq!(edits.borrow().len(), 2);
    assert_eq!(edits.borrow()[1].1.as_str(), "CommandPalette/Commit");
    assert_eq!(edits.borrow()[1].2.as_str(), "asset-name-prompt-confirm");
    assert!(!ui.text_input_focus_active());
}

#[test]
fn u09_command_palette_focused_empty_or_disabled_search_never_commits_raw_query_and_escape_cancels()
{
    for disabled_candidate in [None, Some(true)] {
        let ui = UiHostWindow::new().unwrap();
        ui.set_host_presentation(palette_presentation("关卡 Names", disabled_candidate));
        let edits = Rc::new(RefCell::new(Vec::new()));
        let captured = edits.clone();
        ui.global::<PaneSurfaceHostContext>()
            .on_surface_control_edited(move |control, action, value| {
                captured.borrow_mut().push((control, action, value));
            });
        let clicks = Rc::new(RefCell::new(Vec::new()));
        let captured = clicks.clone();
        ui.global::<PaneSurfaceHostContext>()
            .on_surface_control_clicked(move |control, action| {
                captured.borrow_mut().push((control, action));
            });
        focus_native_search(&ui);
        ui.dispatch_native_key_for_test(
            key_event(Key::Named(NamedKey::Enter), Some("\r")),
            ModifiersState::empty(),
        );
        assert!(edits.borrow().is_empty());
        assert!(ui.text_input_focus_active());
        let result = ui.dispatch_native_key_for_test(
            key_event(Key::Named(NamedKey::Escape), None),
            ModifiersState::empty(),
        );
        assert!(result.request_redraw());
        assert!(!ui.text_input_focus_active());
        assert_eq!(clicks.borrow().len(), 1);
        assert_eq!(clicks.borrow()[0].0.as_str(), "WorkbenchCommandPalette");
        assert_eq!(
            clicks.borrow()[0].1.as_str(),
            crate::ui::retained_host::workbench_popup_actions::WORKBENCH_POPUP_CANCEL_ACTION_ID
        );
    }
}

#[test]
fn u09_command_palette_focus_routing_preserves_ordinary_commit_only_text_input() {
    let ui = UiHostWindow::new().unwrap();
    ui.set_host_presentation(palette_presentation("", Some(false)));
    ui.global::<UiHostContext>()
        .set_text_input_focus(HostTextInputFocusData {
            control_id: "ordinary-setting".into(),
            dispatch_kind: "commit_only".into(),
            edit_action_id: "setting/edit".into(),
            commit_action_id: "setting/commit".into(),
            edit_frame: FrameRect {
                x: 10.0,
                y: 20.0,
                width: 100.0,
                height: 28.0,
            },
            ..Default::default()
        });
    let edits = Rc::new(RefCell::new(Vec::new()));
    let captured = edits.clone();
    ui.global::<PaneSurfaceHostContext>()
        .on_surface_control_edited(move |control, action, value| {
            captured.borrow_mut().push((control, action, value));
        });
    ui.dispatch_native_key_for_test(
        key_event(Key::Character("name".into()), Some("name")),
        ModifiersState::empty(),
    );
    assert!(edits.borrow().is_empty());
    ui.dispatch_native_key_for_test(
        key_event(Key::Named(NamedKey::Enter), Some("\r")),
        ModifiersState::empty(),
    );
    assert_eq!(edits.borrow().len(), 1);
    assert_eq!(edits.borrow()[0].0.as_str(), "ordinary-setting");
    assert_eq!(edits.borrow()[0].1.as_str(), "setting/commit");
    assert_eq!(edits.borrow()[0].2.as_str(), "name");
}

fn focus_native_search(ui: &UiHostWindow) {
    let presentation = ui.get_host_presentation();
    let palette = presentation
        .workbench_window_nodes
        .iter()
        .find(|node| node.control_id.as_str() == "WorkbenchCommandPalette")
        .unwrap();
    let search = command_palette_search_frame(&FrameRect {
        x: palette.frame.x,
        y: palette.frame.y,
        width: palette.frame.width,
        height: palette.frame.height,
    });
    ui.dispatch_native_primary_press_for_test(
        search.x + search.width * 0.5,
        search.y + search.height * 0.5,
    );
    let focus = ui.global::<UiHostContext>().get_text_input_focus();
    assert_eq!(focus.control_id.as_str(), "WorkbenchCommandPalette");
    assert_eq!(focus.dispatch_kind.as_str(), "surface");
}

fn authored_prompt_state(query: &str, has_candidate: bool) -> WorkbenchCommandPaletteOpenState {
    WorkbenchCommandPaletteOpenState {
        query: query.into(),
        commands: UiValue::Array(vec![UiValue::String(
            "asset-name-prompt-confirm|label=Create Folder".into(),
        )]),
        filtered_commands: UiValue::Array(
            has_candidate
                .then(|| UiValue::String("asset-name-prompt-confirm".into()))
                .into_iter()
                .collect(),
        ),
        selected_command_id: "asset-name-prompt-confirm".into(),
        focused_index: if has_candidate { 0 } else { -1 },
        catalog_generation: 0,
        total_match_count: usize::from(has_candidate),
        window_offset: 0,
    }
}

fn palette_presentation(
    query: &str,
    disabled_candidate: Option<bool>,
) -> HostWindowPresentationData {
    HostWindowPresentationData {
        workbench_window_nodes: ModelRc::with_metadata(
            vec![
                TemplatePaneNodeData {
                    control_id: "WorkbenchWindowRoot".into(),
                    role: "Panel".into(),
                    frame: TemplateNodeFrameData {
                        x: 0.0,
                        y: 0.0,
                        width: 800.0,
                        height: 600.0,
                    },
                    ..Default::default()
                },
                TemplatePaneNodeData {
                    control_id: "WorkbenchCommandPalette".into(),
                    role: "CommandPalette".into(),
                    component_role: "command-palette".into(),
                    popup_open: true,
                    edit_action_id: "CommandPalette/QueryChanged".into(),
                    commit_action_id: "CommandPalette/Commit".into(),
                    search_query: query.into(),
                    structured_options: ModelRc::with_metadata(
                        disabled_candidate
                            .map(|disabled| TemplatePaneOptionData {
                                id: "asset-name-prompt-confirm".into(),
                                label: "Confirm".into(),
                                disabled,
                                ..Default::default()
                            })
                            .into_iter()
                            .collect(),
                        (),
                    ),
                    frame: TemplateNodeFrameData {
                        x: 20.25,
                        y: 80.5,
                        width: 360.5,
                        height: 240.0,
                    },
                    ..Default::default()
                },
            ],
            (),
        ),
        ..Default::default()
    }
}

fn key_event(logical_key: Key, text: Option<&str>) -> KeyEvent {
    KeyEvent {
        physical_key: PhysicalKey::Code(KeyCode::KeyN),
        logical_key: logical_key.clone(),
        text: text.map(Into::into),
        location: KeyLocation::Standard,
        state: ElementState::Pressed,
        repeat: false,
        text_with_all_modifiers: text.map(Into::into),
        key_without_modifiers: logical_key,
    }
}

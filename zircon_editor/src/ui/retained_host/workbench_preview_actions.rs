pub(crate) fn is_workbench_preview_action(action_id: &str) -> bool {
    WORKBENCH_PREVIEW_ACTION_IDS.contains(&action_id)
}

#[cfg(test)]
mod tests {
    use super::{is_workbench_preview_action, WORKBENCH_PREVIEW_ACTION_IDS};

    #[test]
    fn workbench_preview_action_registry_covers_module_and_component_lab_samples() {
        for action_id in [
            "SelectWorkbenchModuleEffect",
            "SelectWorkbenchModuleAbility",
            "SelectWorkbenchModuleMaterial",
            "SelectWorkbenchModuleRender",
            "InvokeWorkbenchModuleBrowse",
            "InvokeWorkbenchModuleCompile",
            "EditWorkbenchEffectSearch",
            "SelectWorkbenchEffectTagsTab",
            "SelectWorkbenchEffectModifierHealing",
            "CommitWorkbenchEffectMagnitude",
            "SelectWorkbenchMaterialNodeRoughness",
            "EditWorkbenchMaterialDomain",
            "SelectWorkbenchBehaviorNodeCooldown",
            "SelectWorkbenchAssetsTableTexture",
            "EditWorkbenchVfxSystem",
            "SelectWorkbenchAbilityPhaseCost",
            "EditWorkbenchAbilityName",
            "SelectWorkbenchTagsAbilityActivate",
            "SelectWorkbenchPerceptionSightCone",
            "EditWorkbenchPerceptionConfig",
            "SelectWorkbenchRenderLightingPass",
            "EditWorkbenchRenderPipeline",
            "SelectWorkbenchHudMinimap",
            "EditWorkbenchHudScreen",
            "InvokeWorkbenchAssetsImport",
            "SelectWorkbenchVfxTimelineTab",
            "OpenComponentLabInputDropdown",
            "SelectComponentLabLabsTabTwo",
            "SelectSceneTreeLayersTab",
        ] {
            assert!(
                is_workbench_preview_action(action_id),
                "{action_id} should stay in the shared preview-action registry"
            );
        }
        assert!(!is_workbench_preview_action("OpenProject"));
        let unique_action_count = WORKBENCH_PREVIEW_ACTION_IDS
            .iter()
            .copied()
            .collect::<std::collections::BTreeSet<_>>()
            .len();
        assert_eq!(
            unique_action_count,
            WORKBENCH_PREVIEW_ACTION_IDS.len(),
            "preview action ids should remain unique"
        );
    }
}

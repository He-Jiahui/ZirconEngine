const EXTENSION_PREVIEW_ACTION_COUNT: usize = 754;
const WORKBENCH_EXTENSION_PREVIEW_ACTION_ID_ARRAY: [&str; EXTENSION_PREVIEW_ACTION_COUNT] =
    combine_extension_preview_action_ids();

pub(super) const WORKBENCH_EXTENSION_PREVIEW_ACTION_IDS: &[&str] =
    &WORKBENCH_EXTENSION_PREVIEW_ACTION_ID_ARRAY;

const fn combine_extension_preview_action_ids() -> [&'static str; EXTENSION_PREVIEW_ACTION_COUNT] {
    let quality_and_observability =
        quality_and_observability::QUALITY_AND_OBSERVABILITY_PREVIEW_ACTION_IDS;
    let mut combined = [""; EXTENSION_PREVIEW_ACTION_COUNT];
    let mut output = 0;
    let mut input = 0;
    while input < PRIMARY_EXTENSION_PREVIEW_ACTION_IDS.len() {
        combined[output] = PRIMARY_EXTENSION_PREVIEW_ACTION_IDS[input];
        output += 1;
        input += 1;
    }
    input = 0;
    while input < quality_and_observability.len() {
        combined[output] = quality_and_observability[input];
        output += 1;
        input += 1;
    }
    assert!(output == EXTENSION_PREVIEW_ACTION_COUNT);
    combined
}


/// 用crate资产根嵌入基础原语，避免更深测试目录改变相对路径含义。
macro_rules! workbench_asset {
    ($path:literal) => {
        include_str!(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/assets/ui/editor/components/workbench/",
            $path
        ))
    };
}


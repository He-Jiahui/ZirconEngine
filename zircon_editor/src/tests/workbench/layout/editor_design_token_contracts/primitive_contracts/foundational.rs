#[test]
/// 解析根节点确认可渲染Label直接消费行高比例，单纯导入主题不构成赋值。
fn label_primitives_assign_the_shared_line_height_on_their_root_node() {
    for (asset_name, asset) in [
        (
            "workbench_label.zui",
            workbench_asset!("primitives/data/workbench_label.zui"),
        ),
        (
            "workbench_caption.zui",
            workbench_asset!("primitives/data/workbench_caption.zui"),
        ),
        (
            "workbench_section_title.zui",
            workbench_asset!("primitives/chrome/workbench_section_title.zui"),
        ),
        (
            "workbench_chip.zui",
            workbench_asset!("primitives/chrome/workbench_chip.zui"),
        ),
    ] {
        let document = asset
            .parse::<Value>()
            .unwrap_or_else(|error| panic!("parse `{asset_name}`: {error}"));
        let root = document
            .get("nodes")
            .and_then(Value::as_table)
            .and_then(|nodes| nodes.get("root"))
            .unwrap_or_else(|| panic!("{asset_name} must expose a root node"));
        assert_eq!(
            root.get("component").and_then(Value::as_str),
            Some("Label"),
            "{asset_name} root must remain a renderable label primitive"
        );
        assert_eq!(
            root.get("props")
                .and_then(Value::as_table)
                .and_then(|props| props.get("line_height_ratio"))
                .and_then(Value::as_str),
            Some("$editor.typography.line_height"),
            "{asset_name} must assign the shared line-height token directly on its root"
        );
    }
}

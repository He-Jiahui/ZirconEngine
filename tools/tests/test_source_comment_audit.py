import contextlib
import io
import json
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

from tools import source_comment_audit as audit


class SourceCommentAuditTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.data = self.root / "docs/cli-and-tooling/source-comment-audit"
        subprocess.run(["git", "init", "-q"], cwd=self.root, check=True)

    def write(self, relative: str, content: str | bytes) -> Path:
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content.encode("utf-8") if isinstance(content, str) else content)
        return path

    def run_cli(self, *arguments: str) -> tuple[int, str]:
        output = io.StringIO()
        with contextlib.redirect_stdout(output), contextlib.redirect_stderr(output):
            result = audit.main(
                ["--repo-root", str(self.root), "--data-dir", str(self.data), *arguments]
            )
        return result, output.getvalue()

    def rows(self, relative: str) -> dict[str, dict]:
        return {
            item["path"]: item
            for item in (
                json.loads(line)
                for line in (self.data / relative).read_text(encoding="utf-8").splitlines()
            )
        }

    def test_inventory_classifies_live_source_and_explains_exclusions(self) -> None:
        self.write("zircon_runtime/src/lib.rs", "pub fn start() {}\n")
        self.write("zircon_runtime/tests/script.zr", "pub run() {}\n")
        self.write("templates/projects/example/shader.wgsl", "fn main() {}\n")
        self.write("zircon_editor/assets/ui/editor/modules/generated/panel.zui", "[asset]\nkind = 'component'\n")
        self.write("examples/woc/scripts/src/generated/catalog.zr", "// Generated by tools/codegen.mjs; do not edit by hand.\n")
        self.write("examples/woc/scripts/bin/main.zro", b"\x01ZR\x02\x00")
        self.write("examples/vampire/assets/actor.zmeta", "source_digest = '123'\n")
        self.write("examples/vampire/assets/animation/attack.zranim", "[graph]\nname = 'attack'\n")
        self.write("templates/projects/example/export/desktop.zpreset", "[export]\n")
        self.write("tools/zircon_export/export-templates/macos/Info.plist", "<plist></plist>\n")
        self.write("zircon_plugins/navigation/native/vendor/recastnavigation/lib.cpp", "void f() {}\n")
        self.write("zircon_runtime/.zircon-cache/shader_variants/v1/cache.meta", "digest = '123'\n")
        self.write("tools/session_tray/gen/schemas/windows-schema.json", "{}\n")
        self.write("docs/tests/editor/compile.log", "compilation output\n")
        self.write("docs/plans/review.md", "# A plan\n")
        self.write("zircon_runtime/src/new_extension.zfoo", "some future source syntax\n")
        self.write("dev/UnrealEngine/Source/f.cpp", "void f() {}\n")
        subprocess.run(["git", "add", "zircon_runtime/src/lib.rs"], cwd=self.root, check=True)

        result, _ = self.run_cli("inventory", "--write")
        self.assertEqual(0, result)
        rows = self.rows("inventory.jsonl")
        self.assertEqual("included", rows["zircon_runtime/src/lib.rs"]["scope"])
        self.assertTrue(rows["zircon_runtime/src/lib.rs"]["tracked"])
        self.assertFalse(rows["zircon_runtime/tests/script.zr"]["tracked"])
        self.assertEqual("included", rows["templates/projects/example/shader.wgsl"]["scope"])
        self.assertEqual("included", rows["zircon_editor/assets/ui/editor/modules/generated/panel.zui"]["scope"])
        self.assertEqual("generated", rows["examples/woc/scripts/src/generated/catalog.zr"]["reason"])
        self.assertEqual("binary_output", rows["examples/woc/scripts/bin/main.zro"]["reason"])
        self.assertEqual("generated_metadata", rows["examples/vampire/assets/actor.zmeta"]["reason"])
        self.assertEqual("included", rows["examples/vampire/assets/animation/attack.zranim"]["scope"])
        self.assertEqual("included", rows["templates/projects/example/export/desktop.zpreset"]["scope"])
        self.assertEqual("included", rows["tools/zircon_export/export-templates/macos/Info.plist"]["scope"])
        self.assertEqual("third_party", rows["zircon_plugins/navigation/native/vendor/recastnavigation/lib.cpp"]["reason"])
        self.assertEqual("cache_or_build_output", rows["zircon_runtime/.zircon-cache/shader_variants/v1/cache.meta"]["reason"])
        self.assertEqual("generated", rows["tools/session_tray/gen/schemas/windows-schema.json"]["reason"])
        self.assertEqual("recorded_evidence", rows["docs/tests/editor/compile.log"]["reason"])
        self.assertEqual("unclassified", rows["zircon_runtime/src/new_extension.zfoo"]["scope"])
        self.assertEqual("reference_repository", rows["dev/UnrealEngine/Source/f.cpp"]["reason"])
        self.assertEqual(64, len(rows["zircon_runtime/src/lib.rs"]["source_sha256"]))
        self.assertEqual(0, self.run_cli("inventory", "--check")[0])

    def test_review_freshness_tracks_edits_deletion_and_new_files(self) -> None:
        original = "pub fn start() {}\n"
        self.write("zircon_runtime/src/lib.rs", original)
        self.assertEqual(0, self.run_cli("inventory", "--write")[0])
        self.assertEqual(
            0,
            self.run_cli(
                "mark", "--owner", "runtime", "--path", "zircon_runtime/src/lib.rs",
                "--evidence-ref", "notes/runtime.md#entry", "--disposition", "annotated",
            )[0],
        )
        coverage = self.rows("coverage/runtime.jsonl")["zircon_runtime/src/lib.rs"]
        self.assertEqual("annotated", coverage["disposition"])
        self.assertEqual("notes/runtime.md#entry", coverage["evidence_ref"])
        self.assertEqual(1, json.loads(self.run_cli("status", "--json")[1])["counts"]["reviewed_current"])
        self.assertEqual(0, self.run_cli("verify", "--complete")[0])

        self.write("zircon_runtime/src/lib.rs", original + "// changed\n")
        self.assertEqual(1, json.loads(self.run_cli("status", "--json")[1])["counts"]["stale"])
        self.assertNotEqual(0, self.run_cli("inventory", "--check")[0])
        self.assertNotEqual(0, self.run_cli("verify", "--complete")[0])
        (self.root / "zircon_runtime/src/lib.rs").unlink()
        self.assertEqual(1, json.loads(self.run_cli("status", "--json")[1])["counts"]["missing_source"])
        self.write("zircon_runtime/src/lib.rs", original)
        self.assertEqual(1, json.loads(self.run_cli("status", "--json")[1])["counts"]["reviewed_current"])
        self.write("zircon_runtime/src/new.rs", "pub fn new() {}\n")
        self.assertEqual(1, json.loads(self.run_cli("status", "--json")[1])["counts"]["new_source"])
        self.assertNotEqual(0, self.run_cli("verify", "--complete")[0])

    def test_issue_tags_match_open_ledger_rows_and_ignore_historical_examples(self) -> None:
        self.write(
            "zircon_runtime/src/lib.rs",
            'const EXAMPLE: &str = "// TODO: [CR-runtime-9999] string";\n'
            "// TODO: old historical note\n"
            "// TODO: [CR-runtime-0001] Investigate the loader.\n",
        )
        self.write("zircon_hub/deploy/local/deployment.json", '{}\n')
        self.write("docs/cli-and-tooling/source-comment-audit/README.md", "// BUG: [CR-runtime-8888] sample\n")
        self.assertEqual(0, self.run_cli("inventory", "--write")[0])
        issues = self.data / "issues/runtime.jsonl"
        issues.parent.mkdir(parents=True, exist_ok=True)
        valid = {
            "schema": 1, "id": "CR-runtime-0001", "kind": "TODO",
            "path": "zircon_hub/deploy/local/deployment.json",
            "anchor_path": "zircon_runtime/src/lib.rs", "evidence": "loader call graph",
            "impact_or_question": "Deployment values are consumed without a contract",
            "next_action": "Inspect loader callsites", "existing_owner": "hub-identity",
            "state": "open",
        }
        issues.write_text(json.dumps(valid) + "\n", encoding="utf-8")
        self.assertEqual(0, self.run_cli("verify")[0])

        issues.write_text(json.dumps({**valid, "kind": "BUG"}) + "\n", encoding="utf-8")
        self.assertNotEqual(0, self.run_cli("verify")[0])
        issues.write_text(json.dumps(valid) + "\n" + json.dumps(valid) + "\n", encoding="utf-8")
        self.assertNotEqual(0, self.run_cli("verify")[0])
        issues.write_text("", encoding="utf-8")
        self.assertNotEqual(0, self.run_cli("verify")[0])


    def test_invalid_issue_target_reports_violation_without_crashing(self) -> None:
        self.write("zircon_runtime/src/lib.rs", "// TODO: [CR-runtime-0001] Inspect caller.\n")
        self.assertEqual(0, self.run_cli("inventory", "--write")[0])
        issue_path = self.data / "issues/runtime.jsonl"
        issue_path.parent.mkdir(parents=True, exist_ok=True)
        valid = {
            "schema": 1, "id": "CR-runtime-0001", "kind": "TODO",
            "path": "zircon_runtime/src/lib.rs",
            "anchor_path": "zircon_runtime/src/lib.rs",
            "evidence": "caller scan", "impact_or_question": "caller purpose unclear",
            "next_action": "inspect direct callers", "state": "open",
        }
        for field, invalid in (
            ("path", ["zircon_runtime/src/lib.rs"]),
            ("path", {"unexpected": "object"}),
            ("anchor_path", ["zircon_runtime/src/lib.rs"]),
            ("kind", 7),
            ("state", {"unexpected": "object"}),
        ):
            with self.subTest(field=field, invalid=invalid):
                issue_path.write_text(json.dumps({**valid, field: invalid}) + "\n", encoding="utf-8")
                result, output = self.run_cli("verify")
                self.assertEqual(1, result)
                self.assertIn("CR-runtime-0001", output)


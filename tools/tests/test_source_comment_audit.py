    def test_complete_verification_detects_saved_exclusion_of_live_source(self) -> None:
        self.write("zircon_runtime/src/lib.rs", "pub fn start() {}\n")
        self.assertEqual(0, self.run_cli("inventory", "--write")[0])
        inventory = self.rows("inventory.jsonl")
        source = inventory["zircon_runtime/src/lib.rs"]
        inventory[source["path"]] = {
            **source, "scope": "excluded", "source_sha256": None, "reason": "documentation",
        }
        self.data.joinpath("inventory.jsonl").write_text(
            "".join(json.dumps(row) + "\n" for row in inventory.values()), encoding="utf-8"
        )

        result, output = self.run_cli("status", "--json")
        self.assertEqual(0, result)
        counts = json.loads(output)["counts"]
        self.assertEqual(1, counts["scope_changed"])
        self.assertEqual(1, counts["inventory_drift"])
        self.assertEqual(1, counts["unreviewed"])
        self.assertNotEqual(0, self.run_cli("verify", "--complete")[0])

        coverage = self.data / "coverage/runtime.jsonl"
        coverage.parent.mkdir(parents=True, exist_ok=True)
        coverage.write_text(
            json.dumps({
                "schema": 1, "path": source["path"], "owner": "runtime",
                "reviewed_sha256": source["source_sha256"],
                "reviewed_at": "2026-09-26T00:00:00+00:00", "reviewer": "agent",
                "evidence_ref": "notes.md", "disposition": "annotated",
            }) + "\n",
            encoding="utf-8",
        )
        self.assertNotEqual(0, self.run_cli("verify", "--complete")[0])


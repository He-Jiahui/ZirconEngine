    def test_verify_detects_source_change_between_inventory_and_label_read(self) -> None:
        original = "pub fn start() {}\n"
        self.write("zircon_runtime/src/lib.rs", original)
        self.assertEqual(0, self.run_cli("inventory", "--write")[0])
        self.assertEqual(0, self.run_cli(
            "mark", "--owner", "runtime", "--path", "zircon_runtime/src/lib.rs",
            "--evidence-ref", "notes.md", "--disposition", "annotated",
        )[0])
        actual_scan = audit.scan_inventory

        def scan_then_edit(root: Path, data: Path | None = None):
            snapshot = actual_scan(root, data)
            self.write("zircon_runtime/src/lib.rs", original + "// concurrent edit\n")
            return snapshot

        with patch.object(audit, "scan_inventory", side_effect=scan_then_edit):
            result, output = self.run_cli("verify", "--complete")
        self.assertNotEqual(0, result)
        self.assertIn("source changed after inventory scan", output)


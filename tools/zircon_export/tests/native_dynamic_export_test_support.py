def _write_native_dynamic_package_fixture(
    repo_root: Path,
    package_id: str = "animation",
) -> None:
    package = repo_root / "zircon_plugins" / package_id
    (package / "native").mkdir(parents=True)
    (package / "resources").mkdir()
    (package / "src").mkdir()
    (package / "plugin.toml").write_text(
        "\n".join(
            [
                f'id = "{package_id}"',
                'version = "0.1.0"',
                'default_packaging = ["native_dynamic"]',
            ]
        ),
        encoding="utf-8",
    )
    (package / "native" / f"zircon_plugin_{package_id}.dll").write_text(
        "native dynamic placeholder",
        encoding="utf-8",
    )
    (package / "resources" / f"{package_id}.asset").write_text(
        "resource placeholder",
        encoding="utf-8",
    )
    (package / "src" / "lib.rs").write_text(
        "pub fn should_not_ship() {}",
        encoding="utf-8",
    )


def _write_native_dynamic_report(
    out: Path,
    plugins_dir: Path,
    *,
    native_signing: dict[str, object] | None = None,
    native_notarization: dict[str, object] | None = None,
    profile: str = "windows-release",
) -> None:
    report_dir = out / "stages" / "native_dynamic"
    file_manifest = _native_dynamic_plugins_file_manifest(plugins_dir)
    source_package = out / "zircon_plugins" / "animation"
    source_package.mkdir(parents=True, exist_ok=True)
    source_package.joinpath("plugin.toml").write_text(
        'id = "animation"\n',
        encoding="utf-8",
    )
    report = {
        "stage": "NativeDynamic",
        "profile": profile,
        "fatal": False,
        "diagnostics": [],
        "stage_output": str(report_dir),
        "validate_report": str(out / "stages" / "validate" / "report.json"),
        "target_platform": "windows-x86_64",
        "artifact_extensions": [".dll"],
        "native_plugin_root": str(out / "zircon_plugins"),
        "plugins_dir": str(plugins_dir),
        "loader_manifest": str(plugins_dir / "native_plugins.toml"),
        "file_manifest": file_manifest,
        "content_hash": _native_dynamic_content_hash(file_manifest),
        "native_dynamic_packages": ["animation"],
        "package_exports": [_native_dynamic_package_export()],
        "package_count": 1,
        "native_build_plan": _native_dynamic_build_plan_report(),
        "native_build_execution": _native_dynamic_build_execution_report(),
        "native_signing": _native_dynamic_operation_audit_report(),
        "native_notarization": _native_dynamic_operation_audit_report(),
        "materialized_packages": [
            {
                "package_id": "animation",
                "source": str(source_package),
                "destination": str(plugins_dir / "animation"),
                "package_report": str(
                    plugins_dir / "animation" / "native_dynamic_package.toml"
                ),
                "loadable_artifact_count": 1,
                "loadable_artifacts": [
                    "plugins/animation/native/zircon_plugin_animation.dll"
                ],
            }
        ],
    }
    if native_signing is not None:
        report["native_signing"] = native_signing
    if native_notarization is not None:
        report["native_notarization"] = native_notarization
    report_dir.mkdir(parents=True, exist_ok=True)
    report_dir.joinpath("report.json").write_text(
        json_dumps(report),
        encoding="utf-8",
    )


def _write_native_dynamic_stage_plugins(stage_root: Path) -> Path:
    plugins_dir = stage_root / "plugins"
    package = plugins_dir / "animation"
    package_export = _native_dynamic_package_export()
    abi = package_export["abi"]
    (package / "native").mkdir(parents=True)
    (plugins_dir / "native_plugins.toml").write_text(
        "\n".join(
            [
                "[[plugins]]",
                'id = "animation"',
                'path = "plugins/animation"',
                'manifest = "plugins/animation/plugin.toml"',
                'package_report = "plugins/animation/native_dynamic_package.toml"',
                "",
                "[plugins.abi]",
                f'abi_version = {abi["abi_version"]}',
                f'descriptor_symbol = "{abi["descriptor_symbol"]}"',
                f'descriptor_contract = "{abi["descriptor_contract"]}"',
                f'runtime_entry_source = "{abi["runtime_entry_source"]}"',
                f'editor_entry_source = "{abi["editor_entry_source"]}"',
                f'host_function_table = "{abi["host_function_table"]}"',
                f'entry_report_contract = "{abi["entry_report_contract"]}"',
                f'behavior_contract = "{abi["behavior_contract"]}"',
                f'state_snapshot_contract = "{abi["state_snapshot_contract"]}"',
                f'bridge_method_table = "{abi["bridge_method_table"]}"',
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    (package / "native" / "zircon_plugin_animation.dll").write_text(
        "native dynamic placeholder",
        encoding="utf-8",
    )
    _write_native_dynamic_package_report(package)
    return plugins_dir

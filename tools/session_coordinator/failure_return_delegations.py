from __future__ import annotations

import json
import subprocess
import uuid
from dataclasses import asdict, dataclass
from pathlib import Path

from .baselines import BaselineService, hash_file
from .database import Database
from .leases import lease_paths_overlap
from .models import CoordinatorError, utc_text


_EXECUTABLE_SESSION_STATUSES = frozenset(
    {"active", "resolving_failure", "waiting_validation"}
)


@dataclass(frozen=True, slots=True)
class FailureReturnDelegationProof:
    proof_id: str
    lifecycle_key: str
    origin_session_id: str
    fixing_session_id: str
    origin_plan: str
    fixing_plan: str
    destination_path: str
    content_hash: str
    baseline_epoch: int
    authorization_event_id: int

    def to_dict(self) -> dict[str, object]:
        return asdict(self)

    @classmethod
    def from_dict(cls, value: dict[str, object]) -> "FailureReturnDelegationProof":
        return cls(
            proof_id=str(value["proof_id"]),
            lifecycle_key=str(value["lifecycle_key"]),
            origin_session_id=str(value["origin_session_id"]),
            fixing_session_id=str(value["fixing_session_id"]),
            origin_plan=str(value["origin_plan"]),
            fixing_plan=str(value["fixing_plan"]),
            destination_path=str(value["destination_path"]),
            content_hash=str(value["content_hash"]),
            baseline_epoch=int(value["baseline_epoch"]),
            authorization_event_id=int(value["authorization_event_id"]),
        )


@dataclass(frozen=True, slots=True)
class FailureReturnAuthorization:
    origin_session_id: str
    authorization_event_id: int


class FailureReturnDelegationService:
    """Authorize one origin-owned fixed artifact for one exact closeout."""

    AUTHORIZATION_EVENT = "failure.return_origin_destination_authorized"

    def __init__(
        self,
        database: Database,
        repo_root: str | Path,
        baselines: BaselineService,
    ) -> None:
        self.database = database
        self.repo_root = Path(repo_root).resolve()
        self.baselines = baselines

    def record_authorization(
        self,
        *,
        fixing_session_id: str,
        lifecycle_key: str,
        origin_session_id: str,
        destination_path: str,
        authorization_event_id: int,
    ) -> FailureReturnDelegationProof:
        """Seal the generated bytes after ``failure.return`` materializes them."""
        return self._ensure_proof(
            fixing_session_id=fixing_session_id,
            lifecycle_key=lifecycle_key,
            origin_session_id=origin_session_id,
            destination_path=destination_path,
            authorization_event_id=authorization_event_id,
        )

    def prepare_proofs(
        self,
        *,
        fixing_session_id: str,
        lifecycle_keys: tuple[str, ...],
        manifest_paths: tuple[str, ...],
    ) -> tuple[FailureReturnDelegationProof, ...]:
        """Resolve only explicitly authorized fixed destinations in the manifest."""
        manifest = {self._normalize(path) for path in manifest_paths}
        proofs: list[FailureReturnDelegationProof] = []
        for lifecycle_key in lifecycle_keys:
            authorization = self._authorization_for(
                fixing_session_id, lifecycle_key
            )
            if authorization is None:
                continue
            payload = authorization["payload"]
            destination = self._normalize(str(payload.get("destination", "")))
            if destination not in manifest:
                raise CoordinatorError(
                    "failure_closeout_delegation_manifest_mismatch",
                    "Delegated Failure destination is absent from the exact closeout manifest",
                    details={"path": destination, "lifecycleKey": lifecycle_key},
                )
            proof = self._ensure_proof(
                fixing_session_id=fixing_session_id,
                lifecycle_key=lifecycle_key,
                origin_session_id=str(payload.get("originOwnerSessionId", "")),
                destination_path=destination,
                authorization_event_id=int(authorization["event_id"]),
            )
            self._validate_proof(proof, require_unconsumed=True, require_attribution=True)
            proofs.append(proof)
        return tuple(sorted(proofs, key=lambda item: item.destination_path.casefold()))

    def require_for_commit(
        self,
        *,
        fixing_session_id: str,
        closeout_id: str,
        input_fingerprint: str,
        lifecycle_keys: tuple[str, ...],
        manifest_paths: tuple[str, ...],
        proofs: tuple[FailureReturnDelegationProof, ...],
    ) -> None:
        self._require_binding(
            fixing_session_id=fixing_session_id,
            closeout_id=closeout_id,
            input_fingerprint=input_fingerprint,
            lifecycle_keys=lifecycle_keys,
            manifest_paths=manifest_paths,
            proofs=proofs,
        )
        for proof in proofs:
            self._validate_proof(proof, require_unconsumed=True, require_attribution=True)

    def consume(
        self,
        *,
        fixing_session_id: str,
        closeout_id: str,
        input_fingerprint: str,
        lifecycle_keys: tuple[str, ...],
        manifest_paths: tuple[str, ...],
        proofs: tuple[FailureReturnDelegationProof, ...],
        commit_sha: str,
    ) -> None:
        self._require_binding(
            fixing_session_id=fixing_session_id,
            closeout_id=closeout_id,
            input_fingerprint=input_fingerprint,
            lifecycle_keys=lifecycle_keys,
            manifest_paths=manifest_paths,
            proofs=proofs,
        )
        now = utc_text()
        with self.database.transaction() as connection:
            for proof in proofs:
                row = connection.execute(
                    "SELECT * FROM failure_return_delegation_proofs WHERE proof_id=?",
                    (proof.proof_id,),
                ).fetchone()
                if row is None or self._from_row(row) != proof:
                    raise CoordinatorError(
                        "failure_closeout_delegation_proof_mismatch",
                        "Prepared delegated Failure proof no longer matches durable state",
                        details={"proofId": proof.proof_id},
                    )
                if row["consumed_at"] is not None:
                    if (
                        row["consumed_closeout_id"] == closeout_id
                        and row["consumed_input_fingerprint"] == input_fingerprint
                        and row["consumed_commit_sha"] == commit_sha
                    ):
                        continue
                    raise CoordinatorError(
                        "failure_closeout_delegation_replayed",
                        "Delegated Failure return proof was already consumed",
                        details={"proofId": proof.proof_id},
                    )
                updated = connection.execute(
                    """UPDATE failure_return_delegation_proofs
                       SET consumed_closeout_id=?, consumed_input_fingerprint=?,
                           consumed_commit_sha=?, consumed_at=?
                       WHERE proof_id=? AND consumed_at IS NULL""",
                    (
                        closeout_id,
                        input_fingerprint,
                        commit_sha,
                        now,
                        proof.proof_id,
                    ),
                ).rowcount
                if updated != 1:
                    raise CoordinatorError(
                        "failure_closeout_delegation_replayed",
                        "Delegated Failure return proof was already consumed",
                        details={"proofId": proof.proof_id},
                    )

    def _ensure_proof(
        self,
        *,
        fixing_session_id: str,
        lifecycle_key: str,
        origin_session_id: str,
        destination_path: str,
        authorization_event_id: int,
    ) -> FailureReturnDelegationProof:
        destination = self._normalize(destination_path)
        content_hash = hash_file(self.repo_root / destination)
        if content_hash is None:
            raise CoordinatorError(
                "failure_closeout_delegation_destination_missing",
                "Delegated Failure destination is missing",
                details={"path": destination},
            )
        baseline = self.baselines.current()
        _event, node, _origin, _fixing = self._authorization_context(
            fixing_session_id=fixing_session_id,
            lifecycle_key=lifecycle_key,
            origin_session_id=origin_session_id,
            destination_path=destination,
            authorization_event_id=authorization_event_id,
        )
        with self.database.connect() as connection:
            prior = connection.execute(
                """SELECT * FROM failure_return_delegation_proofs
                   WHERE authorization_event_id=? ORDER BY baseline_epoch DESC""",
                (authorization_event_id,),
            ).fetchall()
        if prior and any(row["content_hash"] != content_hash for row in prior):
            raise CoordinatorError(
                "failure_closeout_delegation_content_drift",
                "Delegated Failure destination bytes changed after authorization",
                details={"path": destination},
            )
        matching = next(
            (
                row
                for row in prior
                if int(row["baseline_epoch"]) == baseline.epoch_id
                and row["content_hash"] == content_hash
            ),
            None,
        )
        if matching is not None:
            return self._from_row(matching)
        proof_id = uuid.uuid4().hex
        with self.database.transaction() as connection:
            connection.execute(
                """INSERT INTO failure_return_delegation_proofs(
                       proof_id, lifecycle_key, origin_session_id, fixing_session_id,
                       origin_plan, fixing_plan, destination_path, destination_key,
                       content_hash, baseline_epoch, authorization_event_id, authorized_at
                   ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)""",
                (
                    proof_id,
                    lifecycle_key,
                    origin_session_id,
                    fixing_session_id,
                    str(node["origin_plan"]),
                    str(node["fixing_plan"]),
                    destination,
                    destination.casefold(),
                    content_hash,
                    baseline.epoch_id,
                    authorization_event_id,
                    utc_text(),
                ),
            )
            row = connection.execute(
                "SELECT * FROM failure_return_delegation_proofs WHERE proof_id=?",
                (proof_id,),
            ).fetchone()
        return self._from_row(row)

    def _validate_proof(
        self,
        proof: FailureReturnDelegationProof,
        *,
        require_unconsumed: bool,
        require_attribution: bool,
    ) -> None:
        with self.database.connect() as connection:
            row = connection.execute(
                "SELECT * FROM failure_return_delegation_proofs WHERE proof_id=?",
                (proof.proof_id,),
            ).fetchone()
        if row is None or self._from_row(row) != proof:
            raise CoordinatorError(
                "failure_closeout_delegation_proof_mismatch",
                "Prepared delegated Failure proof no longer matches durable state",
                details={"proofId": proof.proof_id},
            )
        if require_unconsumed and row["consumed_at"] is not None:
            raise CoordinatorError(
                "failure_closeout_delegation_replayed",
                "Delegated Failure return proof was already consumed",
                details={"proofId": proof.proof_id},
            )
        baseline = self.baselines.current()
        if baseline.epoch_id != proof.baseline_epoch or self._head() != baseline.head_commit:
            raise CoordinatorError(
                "failure_closeout_delegation_baseline_drift",
                "Delegated Failure proof belongs to another baseline or HEAD",
                details={"proofId": proof.proof_id},
            )
        content_hash = hash_file(self.repo_root / proof.destination_path)
        if content_hash != proof.content_hash:
            raise CoordinatorError(
                "failure_closeout_delegation_content_drift",
                "Delegated Failure destination bytes changed after authorization",
                details={"path": proof.destination_path},
            )
        _event, node, _origin, _fixing = self._authorization_context(
            fixing_session_id=proof.fixing_session_id,
            lifecycle_key=proof.lifecycle_key,
            origin_session_id=proof.origin_session_id,
            destination_path=proof.destination_path,
            authorization_event_id=proof.authorization_event_id,
        )
        if (
            proof.origin_plan != node["origin_plan"]
            or proof.fixing_plan != node["fixing_plan"]
        ):
            raise CoordinatorError(
                "failure_closeout_delegation_proof_mismatch",
                "Delegated Failure proof plans no longer match the fixed graph",
                details={"proofId": proof.proof_id},
            )
        self._require_origin_lease(proof)
        if require_attribution:
            with self.database.connect() as connection:
                attribution = connection.execute(
                    "SELECT session_id, content_hash FROM attributions WHERE path_key=?",
                    (proof.destination_path.casefold(),),
                ).fetchone()
            if (
                attribution is None
                or attribution["session_id"] != proof.origin_session_id
                or attribution["content_hash"] != proof.content_hash
            ):
                raise CoordinatorError(
                    "failure_closeout_delegation_attribution_drift",
                    "Delegated Failure destination is no longer attributed to its origin owner",
                    details={"path": proof.destination_path},
                )

    def _authorization_context(
        self,
        *,
        fixing_session_id: str,
        lifecycle_key: str,
        origin_session_id: str,
        destination_path: str,
        authorization_event_id: int,
    ):
        with self.database.connect() as connection:
            event = connection.execute(
                "SELECT * FROM events WHERE event_id=?",
                (authorization_event_id,),
            ).fetchone()
            node = connection.execute(
                """SELECT lifecycle_key, artifact_path, origin_plan, fixing_plan,
                          kind, status FROM failure_nodes WHERE lifecycle_key=?""",
                (lifecycle_key,),
            ).fetchone()
            origin = connection.execute(
                "SELECT session_id, plan_path, status FROM sessions WHERE session_id=?",
                (origin_session_id,),
            ).fetchone()
            fixing = connection.execute(
                "SELECT session_id, plan_path, status FROM sessions WHERE session_id=?",
                (fixing_session_id,),
            ).fetchone()
        if event is None or event["event_type"] != self.AUTHORIZATION_EVENT:
            raise CoordinatorError(
                "failure_closeout_delegation_authorization_missing",
                "Delegated Failure proof lacks its immutable authorization event",
            )
        try:
            payload = json.loads(event["payload_json"])
        except (TypeError, json.JSONDecodeError) as error:
            raise CoordinatorError(
                "failure_closeout_delegation_authorization_invalid",
                "Delegated Failure authorization payload is invalid",
            ) from error
        expected_payload = {
            "lifecycleKey": lifecycle_key,
            "destination": destination_path,
            "originOwnerSessionId": origin_session_id,
        }
        if (
            event["session_id"] != fixing_session_id
            or any(payload.get(key) != value for key, value in expected_payload.items())
            or node is None
            or node["kind"] != "fixed"
            or node["status"] != "fixed"
            or self._normalize(str(node["artifact_path"])) != destination_path
            or origin is None
            or fixing is None
            or origin["status"] not in _EXECUTABLE_SESSION_STATUSES
            or fixing["status"] != "resolving_failure"
            or origin_session_id == fixing_session_id
            or origin["plan_path"] != node["origin_plan"]
            or fixing["plan_path"] != node["fixing_plan"]
            or payload.get("originPlan") != node["origin_plan"]
        ):
            raise CoordinatorError(
                "failure_closeout_delegation_authorization_drift",
                "Delegated Failure authorization no longer matches graph and Session ownership",
                details={"lifecycleKey": lifecycle_key, "path": destination_path},
            )
        return event, node, origin, fixing

    def _authorization_for(
        self, fixing_session_id: str, lifecycle_key: str
    ) -> dict[str, object] | None:
        with self.database.connect() as connection:
            rows = connection.execute(
                """SELECT event_id, payload_json FROM events
                   WHERE session_id=? AND event_type=? ORDER BY event_id DESC""",
                (fixing_session_id, self.AUTHORIZATION_EVENT),
            ).fetchall()
        for row in rows:
            try:
                payload = json.loads(row["payload_json"])
            except (TypeError, json.JSONDecodeError):
                continue
            if payload.get("lifecycleKey") == lifecycle_key:
                return {"event_id": int(row["event_id"]), "payload": payload}
        return None

    def _require_origin_lease(self, proof: FailureReturnDelegationProof) -> None:
        now = utc_text()
        with self.database.connect() as connection:
            rows = connection.execute(
                "SELECT path_key, session_id FROM leases WHERE expires_at>=?",
                (now,),
            ).fetchall()
        overlapping = [
            row
            for row in rows
            if lease_paths_overlap(str(row["path_key"]), proof.destination_path.casefold())
        ]
        if not overlapping or any(
            row["session_id"] != proof.origin_session_id for row in overlapping
        ):
            raise CoordinatorError(
                "failure_closeout_delegation_origin_lease_missing",
                "Delegated Failure destination requires its active origin-owner lease",
                details={"path": proof.destination_path},
            )

    @staticmethod
    def _require_binding(
        *,
        fixing_session_id: str,
        closeout_id: str,
        input_fingerprint: str,
        lifecycle_keys: tuple[str, ...],
        manifest_paths: tuple[str, ...],
        proofs: tuple[FailureReturnDelegationProof, ...],
    ) -> None:
        manifest = {path.replace("\\", "/") for path in manifest_paths}
        lifecycle_set = set(lifecycle_keys)
        if (
            not closeout_id
            or len(input_fingerprint) != 64
            or any(proof.fixing_session_id != fixing_session_id for proof in proofs)
            or any(proof.lifecycle_key not in lifecycle_set for proof in proofs)
            or any(proof.destination_path not in manifest for proof in proofs)
            or len({proof.destination_path.casefold() for proof in proofs}) != len(proofs)
        ):
            raise CoordinatorError(
                "failure_closeout_delegation_binding_mismatch",
                "Delegated Failure proofs do not match the exact closeout identity",
            )

    @staticmethod
    def _from_row(row) -> FailureReturnDelegationProof:
        return FailureReturnDelegationProof(
            proof_id=str(row["proof_id"]),
            lifecycle_key=str(row["lifecycle_key"]),
            origin_session_id=str(row["origin_session_id"]),
            fixing_session_id=str(row["fixing_session_id"]),
            origin_plan=str(row["origin_plan"]),
            fixing_plan=str(row["fixing_plan"]),
            destination_path=str(row["destination_path"]),
            content_hash=str(row["content_hash"]),
            baseline_epoch=int(row["baseline_epoch"]),
            authorization_event_id=int(row["authorization_event_id"]),
        )

    @staticmethod
    def _normalize(path: str) -> str:
        normalized = path.replace("\\", "/").strip("/")
        if not normalized or Path(normalized).is_absolute() or ".." in Path(normalized).parts:
            raise CoordinatorError(
                "failure_closeout_delegation_path_invalid",
                "Delegated Failure destination must be a repository-relative path",
                details={"path": path},
            )
        return normalized

    def _head(self) -> str:
        return subprocess.run(
            ["git", "rev-parse", "HEAD"],
            cwd=self.repo_root,
            check=True,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        ).stdout.strip()

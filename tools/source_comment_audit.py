DEFAULT_DATA = "docs/cli-and-tooling/source-comment-audit"
SCHEMA = 1
SOURCE_SUFFIXES = {
    ".rs", ".py", ".ps1", ".psm1", ".mjs", ".js", ".ts", ".tsx",
    ".css", ".html", ".wgsl", ".h", ".hpp", ".c", ".cpp", ".mm",
    ".metal", ".zr", ".zui", ".sql", ".sh", ".bat", ".cmd",
    ".zrp", ".zshader", ".zmaterial", ".toml", ".json", ".yaml", ".yml",
    ".zranim", ".zpreset", ".plist",
}
DOCUMENT_SUFFIXES = {".md", ".rst", ".txt", ".pdf", ".lock"}
RECORDED_SUFFIXES = {".log", ".exit"}
BINARY_SUFFIXES = {
    ".zro", ".zasset", ".png", ".jpg", ".jpeg", ".webp", ".gif",
    ".ico", ".svg", ".glb", ".gltf", ".blend", ".ttf", ".otf",
    ".woff", ".woff2", ".mp3", ".wav", ".mp4", ".rdc", ".dll",
    ".so", ".dylib", ".exe", ".pdb", ".lib", ".a", ".o",
    ".usdc", ".zip", ".hdr", ".ttc", ".zribl", ".zcube", ".pbm",
    ".obj", ".zst", ".bin",
}
DISPOSITIONS = {"annotated", "no_comment_needed", "issue_only", "reviewed_resource"}
LABEL = re.compile(
    r"^\s*(?://|#|--|/\*+|\*|<!--)\s*"
    r"(?P<kind>TODO|BUG):\s*\[(?P<id>CR-[A-Za-z0-9_-]+-\d{4,})\]"
)
ISSUE_ID = re.compile(r"^CR-[A-Za-z][A-Za-z0-9_-]*-\d{4,}$")
OWNER = re.compile(r"^[A-Za-z][A-Za-z0-9_-]*$")
DIGEST = re.compile(r"^[0-9a-f]{64}$")
GENERATED_HEADER = re.compile(
    rb"^\s*(?://|#|/\*|<!--)\s*(?:@generated\b|generated by\b|auto.?generated\b)",
    re.IGNORECASE,
)


class AuditError(Exception):
    """源清单或审查证据不满足可核对契约。"""


def _git_paths(root: Path, *arguments: str) -> set[str]:
    environment = os.environ.copy()
    environment["GIT_OPTIONAL_LOCKS"] = "0"
    result = subprocess.run(
        ["git", "ls-files", *arguments, "-z"],
        cwd=root,
        env=environment,
        capture_output=True,
        check=True,
    )
    return {
        item.decode("utf-8", errors="surrogateescape").replace("\\", "/")
        for item in result.stdout.split(b"\0") if item
    }


def _validate_relative(path: str) -> str:
    normalized = path.replace("\\", "/")
    parsed = PurePosixPath(normalized)
    if (
        not normalized or parsed.is_absolute() or ":" in normalized
        or any(part in {"", ".", ".."} for part in normalized.split("/"))
    ):
        raise AuditError(f"invalid repository-relative path: {path!r}")
    return normalized


def _guard_file(root: Path, relative: str) -> Path:
    path = root / _validate_relative(relative)
    current = path
    while current != root:
        if current.is_symlink() or (hasattr(current, "is_junction") and current.is_junction()):
            raise AuditError(f"linked source path is outside the audit boundary: {relative}")
        current = current.parent
    return path


def _stable_digest(path: Path) -> tuple[str, bytes]:
    # 标记识别和哈希必须来自同一读取窗口，否则并行编辑可能让生成物被当作手写源码。
    before = path.stat(follow_symlinks=False)
    digest = hashlib.sha256()
    header = b""
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            if not header:
                header = chunk[:4096]
            digest.update(chunk)
    after = path.stat(follow_symlinks=False)
    identity = lambda stat: (stat.st_ino, stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns)
    if identity(before) != identity(after):
        raise AuditError(f"source changed while being hashed: {path}")
    return digest.hexdigest(), header


def _scope(relative: str, header: bytes) -> tuple[str, str, str | None]:
    parts = PurePosixPath(relative).parts
    suffix = PurePosixPath(relative).suffix.lower()
    kind = suffix.removeprefix(".") or "extensionless"
    if parts[0] == "dev":
        return "excluded", kind, "reference_repository"
    if any(part in {"vendor", "third_party", "third-party"} for part in parts):
        return "excluded", kind, "third_party"
    if parts[:5] == ("docs", "tests", "runtime", "shader", "assets") and any(
        part.startswith("ambientcg_") for part in parts[5:]
    ):
        return "excluded", kind, "third_party_fixture"
    if parts[0] in {"artifacts", "stage", "worktrees", "node_modules"} or any(
        part in {"node_modules", "target", ".cache", ".zircon-cache", ".work", ".git", ".zig-cache"}
        or part.startswith("target-") for part in parts
    ):
        return "excluded", kind, "cache_or_build_output"
    if parts[:3] == ("docs", "cli-and-tooling", "source-comment-audit"):
        return "excluded", kind, "audit_record"
    if parts[:3] == ("tools", "session_tray", "gen") or parts[:3] == (
        "tools", "session_tray", "dist"
    ):
        return "excluded", kind, "generated"
    if "dist" in parts and parts[0] == "zircon_hub":
        return "excluded", kind, "cache_or_build_output"
    if suffix == ".zmeta":
        return "excluded", kind, "generated_metadata"
    if suffix == ".zro":
        return "excluded", kind, "binary_output"
    if suffix == ".host-placeholder":
        return "excluded", kind, "build_placeholder"
    if parts[-1] == ".gitignore":
        return "excluded", kind, "repository_metadata"
    if parts[-1] == ".zr_cli_manifest":
        return "excluded", kind, "generated"
    if suffix in BINARY_SUFFIXES or b"\0" in header or (header and not _is_text(header)):
        return "excluded", kind, "binary_asset"
    first_lines = header.splitlines()[:3]
    if any(GENERATED_HEADER.match(line) for line in first_lines) or any(
        line.lstrip().startswith((b"//", b"#", b"/*"))
        and b"do not edit by hand" in line.lower() for line in first_lines
    ):
        return "excluded", kind, "generated"
    if relative == "requirements-docs.txt":
        return "included", kind, None
    if suffix in DOCUMENT_SUFFIXES or relative in {".gitignore", "AGENTS.md", "LICENSE"}:
        return "excluded", kind, "documentation"
    if suffix in RECORDED_SUFFIXES or (
        suffix in {".jsonl", ".csv"} and parts[:4] == ("docs", "tests", "runtime", "text")
    ):
        return "excluded", kind, "recorded_evidence"
    if relative == ".rustc_info.json":
        return "excluded", kind, "cache_or_build_output"
    if "/evidence/" in f"/{relative}" and parts[0] == "docs":
        return "excluded", kind, "recorded_evidence"
    if suffix in SOURCE_SUFFIXES:
        return "included", kind, None
    if not header or _is_text(header):
        return "unclassified", kind, "unknown_text_suffix"
    return "excluded", kind, "binary_asset"


def _is_text(header: bytes) -> bool:
    try:
        # 固定长度前缀可能截断最后一个多字节字符；仅允许这种未完成尾部。
        codecs.getincrementaldecoder("utf-8")("strict").decode(header, final=False)
    except UnicodeDecodeError:
        return False
    return not any(byte < 32 and byte not in (9, 10, 13) for byte in header)


def _inventory_row(root: Path, relative: str, tracked: bool) -> dict[str, Any]:
    path = _guard_file(root, relative)
    if not path.is_file():
        scope, kind, _reason = _scope(relative, b"")
        return {
            "schema": SCHEMA, "path": relative, "scope": scope, "kind": kind,
            "source_sha256": None, "reason": "missing_worktree_file", "tracked": tracked,
        }
    preliminary_scope, preliminary_kind, preliminary_reason = _scope(relative, b"")
    suffix = PurePosixPath(relative).suffix.lower()
    if preliminary_scope == "excluded" and (
        preliminary_reason != "binary_asset" or suffix in BINARY_SUFFIXES
    ):
        scope, kind, reason, digest = (
            preliminary_scope, preliminary_kind, preliminary_reason, None
        )
    else:
        # 一次稳定读取同时确定范围和内容身份，避免“先分类后修改”的窗口。
        digest, header = _stable_digest(path)
        scope, kind, reason = _scope(relative, header)
    return {
        "schema": SCHEMA, "path": relative, "scope": scope, "kind": kind,
        "source_sha256": digest if scope != "excluded" else None,
        "reason": reason, "tracked": tracked,
    }


def scan_inventory(root: Path, data: Path | None = None) -> dict[str, dict[str, Any]]:
    tracked = _git_paths(root, "--cached")
    excluded_prefixes = {DEFAULT_DATA + "/"}
    if data is not None and data.is_relative_to(root):
        excluded_prefixes.add(data.relative_to(root).as_posix().rstrip("/") + "/")
    # 账本自身不属于审查输入，避免 inventory --write 立即让下一次 --check 失效。
    visible = {
        path for path in tracked | _git_paths(root, "--others", "--exclude-standard")
        if not any(path.startswith(prefix) for prefix in excluded_prefixes)
    }
    by_case: dict[str, str] = {}
    for path in visible:
        folded = path.casefold()
        if folded in by_case and by_case[folded] != path:
            raise AuditError(f"case-colliding repository paths: {by_case[folded]} and {path}")
        by_case[folded] = path
    paths = sorted(visible, key=lambda path: (path.casefold(), path))
    with ThreadPoolExecutor(max_workers=8) as executor:
        rows = executor.map(lambda path: _inventory_row(root, path, path in tracked), paths)
        return {row["path"]: row for row in rows}


def _read_jsonl(path: Path, key: str) -> dict[str, dict[str, Any]]:
    if not path.is_file():
        raise AuditError(f"missing audit ledger: {path}")
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except UnicodeDecodeError as error:
        raise AuditError(f"invalid UTF-8 audit ledger: {path}") from error
    rows: dict[str, dict[str, Any]] = {}
    for line_number, line in enumerate(lines, 1):
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError as error:
            raise AuditError(f"invalid JSONL at {path}:{line_number}: {error}") from error
        if not isinstance(row, dict) or row.get("schema") != SCHEMA or not isinstance(row.get(key), str):
            raise AuditError(f"invalid audit record at {path}:{line_number}")
        value = row[key]
        if value in rows:
            raise AuditError(f"duplicate {key} {value!r} at {path}:{line_number}")
        rows[value] = row
    return rows


def _read_shards(directory: Path, key: str) -> dict[str, dict[str, Any]]:
    rows: dict[str, dict[str, Any]] = {}
    if not directory.is_dir():
        return rows
    for path in sorted(directory.glob("*.jsonl")):
        for value, row in _read_jsonl(path, key).items():
            if directory.name == "coverage" and row.get("owner") != path.stem:
                raise AuditError(
                    f"review owner {row.get('owner')!r} does not match coverage shard {path}"
                )
            if value in rows:
                raise AuditError(f"duplicate {key} {value!r} across audit shards")
            rows[value] = row
    return rows


def _validated_coverage(data: Path) -> dict[str, dict[str, Any]]:
    coverage = _read_shards(data / "coverage", "path")
    for relative, row in coverage.items():
        _validate_relative(relative)
        for field in ("owner", "reviewed_at", "reviewer", "evidence_ref"):
            if not isinstance(row.get(field), str) or not row[field].strip():
                raise AuditError(f"review record lacks {field}: {relative}")
        if not OWNER.fullmatch(row["owner"]):
            raise AuditError(f"invalid review owner: {relative}")
        if not isinstance(row.get("disposition"), str) or row["disposition"] not in DISPOSITIONS:
            raise AuditError(f"invalid review disposition: {relative}")
        if not isinstance(row.get("reviewed_sha256"), str) or not DIGEST.fullmatch(row["reviewed_sha256"]):
            raise AuditError(f"invalid reviewed source hash: {relative}")
    return coverage


def _write_jsonl(path: Path, rows: dict[str, dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    pending: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", newline="\n", dir=path.parent,
            prefix=f".{path.name}.", suffix=".tmp", delete=False,
        ) as stream:
            pending = Path(stream.name)
            for key in sorted(rows, key=lambda item: (item.casefold(), item)):
                stream.write(json.dumps(rows[key], ensure_ascii=False, sort_keys=True) + "\n")
        os.replace(pending, path)
    finally:
        if pending is not None:
            pending.unlink(missing_ok=True)


def _review_write_lock_path(data: Path) -> Path:
    canonical = os.path.normcase(str(data.resolve()))
    digest = hashlib.sha256(os.fsencode(canonical)).hexdigest()
    return Path(tempfile.gettempdir()) / "zircon-source-comment-audit-locks" / f"{digest}.lock"


@contextmanager
def _review_write_lock(data: Path):
    """Serialize all owners' review decisions for one audit ledger directory."""
    lock_path = _review_write_lock_path(data)
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    # Keep the lock file after release: unlinking it can split concurrent writers across inodes.
    with lock_path.open("a+b") as stream:
        if stream.seek(0, os.SEEK_END) == 0:
            stream.write(b"\0")
            stream.flush()
        stream.seek(0)
        try:
            if os.name == "nt":
                import msvcrt

                msvcrt.locking(stream.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl

                fcntl.flock(stream.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as error:
            if error.errno in {errno.EACCES, errno.EAGAIN, errno.EDEADLK} or getattr(error, "winerror", None) in {33, 36}:
                raise AuditError(f"review write already in progress for {data}") from error
            raise
        try:
            yield
        finally:
            stream.seek(0)
            if os.name == "nt":
                msvcrt.locking(stream.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(stream.fileno(), fcntl.LOCK_UN)


def inventory_command(root: Path, data: Path, *, write: bool) -> int:
    current = scan_inventory(root, data)
    target = data / "inventory.jsonl"
    if write:
        _write_jsonl(target, current)
        print(json.dumps({"file_count": len(current), "inventory": str(target)}))
        return 0
    saved = _read_jsonl(target, "path")
    added = sorted(current.keys() - saved.keys())
    removed = sorted(saved.keys() - current.keys())
    changed = sorted(path for path in current.keys() & saved.keys() if current[path] != saved[path])
    print(json.dumps({"added": added, "removed": removed, "changed": changed}, ensure_ascii=False))
    return 1 if added or removed or changed else 0


def mark_command(root: Path, data: Path, arguments: argparse.Namespace) -> int:
    with _review_write_lock(data):
        return _mark_command_locked(root, data, arguments)


def _mark_command_locked(root: Path, data: Path, arguments: argparse.Namespace) -> int:
    owner = arguments.owner
    if not OWNER.fullmatch(owner):
        raise AuditError(f"invalid module owner: {owner!r}")
    relative = _validate_relative(arguments.path)
    inventory = _read_jsonl(data / "inventory.jsonl", "path")
    if relative not in inventory or inventory[relative]["scope"] != "included":
        raise AuditError(f"path is not an inventoried first-party source: {relative}")
    if not arguments.evidence_ref.strip():
        raise AuditError("review evidence reference must not be empty")
    path = _guard_file(root, relative)
    if not path.is_file():
        raise AuditError(f"reviewed source is missing: {relative}")
    digest, header = _stable_digest(path)
    if _scope(relative, header)[0] != "included":
        raise AuditError(f"source classification changed since inventory: {relative}")
    all_coverage = _validated_coverage(data)
    previous = all_coverage.get(relative)
    if previous and previous.get("owner") != owner:
        raise AuditError(f"source is already reviewed by owner {previous.get('owner')}: {relative}")
    shard_path = data / "coverage" / f"{owner}.jsonl"
    shard = _read_jsonl(shard_path, "path") if shard_path.is_file() else {}
    shard[relative] = {
        "schema": SCHEMA, "path": relative, "owner": owner,
        "reviewed_sha256": digest,
        "reviewed_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "reviewer": arguments.reviewer or owner,
        "evidence_ref": arguments.evidence_ref.strip(),
        "disposition": arguments.disposition,
    }
    _write_jsonl(shard_path, shard)
    print(json.dumps({"path": relative, "reviewed_sha256": digest, "owner": owner}))
    return 0


def mark_batch_command(root: Path, data: Path, arguments: argparse.Namespace) -> int:
    with _review_write_lock(data):
        return _mark_batch_command_locked(root, data, arguments)


def _mark_batch_command_locked(root: Path, data: Path, arguments: argparse.Namespace) -> int:
    owner = arguments.owner
    if not OWNER.fullmatch(owner):
        raise AuditError(f"invalid module owner: {owner!r}")
    shard_path = data / "coverage" / f"{owner}.jsonl"
    input_path = arguments.input_file.resolve()
    if input_path == shard_path:
        raise AuditError("batch input cannot be the coverage shard being updated")
    input_digest, _header = _stable_digest(input_path)
    batch = _read_jsonl(input_path, "path")
    if not batch:
        raise AuditError("review batch must contain at least one file")
    if _stable_digest(input_path)[0] != input_digest:
        raise AuditError("review batch input changed while being parsed")

    inventory = _read_jsonl(data / "inventory.jsonl", "path")
    coverage = _validated_coverage(data)
    shard = {
        relative: row for relative, row in coverage.items() if row["owner"] == owner
    }
    now = datetime.now(timezone.utc).isoformat(timespec="seconds")
    prepared: list[tuple[str, Path, str]] = []
    changed = 0
    allowed_fields = {
        "schema", "path", "expected_sha256", "evidence_ref", "disposition", "reviewer"
    }
    for relative, item in batch.items():
        if _validate_relative(relative) != relative:
            raise AuditError(f"batch path must use forward slashes: {relative}")
        if set(item) - allowed_fields:
            raise AuditError(f"unknown review batch fields for {relative}: {sorted(set(item) - allowed_fields)}")
        expected = item.get("expected_sha256")
        if not isinstance(expected, str) or not DIGEST.fullmatch(expected):
            raise AuditError(f"batch review requires a lowercase SHA-256 hash: {relative}")
        evidence = item.get("evidence_ref")
        if not isinstance(evidence, str) or not evidence.strip():
            raise AuditError(f"batch review requires per-file evidence: {relative}")
        disposition = item.get("disposition")
        if not isinstance(disposition, str) or disposition not in DISPOSITIONS:
            raise AuditError(f"invalid batch review disposition: {relative}")
        reviewer = item.get("reviewer", arguments.reviewer or owner)
        if not isinstance(reviewer, str) or not reviewer.strip():
            raise AuditError(f"invalid batch reviewer: {relative}")
        if relative not in inventory or inventory[relative]["scope"] != "included":
            raise AuditError(f"path is not an inventoried first-party source: {relative}")
        previous = coverage.get(relative)
        if previous and previous["owner"] != owner:
            raise AuditError(f"source is already reviewed by owner {previous['owner']}: {relative}")
        path = _guard_file(root, relative)
        if not path.is_file():
            raise AuditError(f"reviewed source is missing: {relative}")
        digest, header = _stable_digest(path)
        if digest != expected:
            raise AuditError(f"reviewed source hash differs from batch expectation: {relative}")
        if _scope(relative, header)[0] != "included":
            raise AuditError(f"source classification changed since inventory: {relative}")
        prepared.append((relative, path, expected))
        if previous and all(previous.get(field) == value for field, value in (
            ("reviewed_sha256", expected), ("evidence_ref", evidence.strip()),
            ("disposition", disposition), ("reviewer", reviewer.strip()),
        )):
            continue
        shard[relative] = {
            "schema": SCHEMA, "path": relative, "owner": owner,
            "reviewed_sha256": expected, "reviewed_at": now,
            "reviewer": reviewer.strip(), "evidence_ref": evidence.strip(),
            "disposition": disposition,
        }
        changed += 1

    # 大批次里最早核对的文件可能已被并行会话改动；发布前再次核对全部输入。
    if _stable_digest(input_path)[0] != input_digest:
        raise AuditError("review batch input changed before publication")
    for relative, path, expected in prepared:
        digest, header = _stable_digest(path)
        if digest != expected or _scope(relative, header)[0] != "included":
            raise AuditError(f"reviewed source changed before batch publication: {relative}")
    if changed:
        _write_jsonl(shard_path, shard)
    print(json.dumps({"owner": owner, "submitted": len(batch), "updated": changed,
                      "unchanged": len(batch) - changed, "coverage": str(shard_path)}))
    return 0


def review_status(
    root: Path, data: Path, live: dict[str, dict[str, Any]] | None = None
) -> dict[str, Any]:
    saved = _read_jsonl(data / "inventory.jsonl", "path")
    live = live if live is not None else scan_inventory(root, data)
    coverage = _validated_coverage(data)
    paths: dict[str, list[str]] = {
        name: [] for name in (
            "reviewed_current", "unreviewed", "stale", "missing_source",
            "new_source", "unclassified", "new_excluded", "scope_changed",
            "orphan_review", "inventory_drift", "excluded",
        )
    }
    for relative, row in live.items():
        if row["scope"] == "unclassified":
            paths["unclassified"].append(relative)
        elif row["scope"] == "excluded":
            paths["excluded"].append(relative)
        previous = saved.get(relative)
        if previous is None:
            paths["new_source" if row["scope"] == "included" else "new_excluded"].append(relative)
        else:
            if previous != row:
                paths["inventory_drift"].append(relative)
            if previous.get("scope") != row["scope"]:
                paths["scope_changed"].append(relative)
        if row["scope"] != "included":
            continue
        if row["source_sha256"] is None:
            paths["missing_source"].append(relative)
            continue
        review = coverage.get(relative)
        if review is None:
            paths["unreviewed"].append(relative)
        elif review.get("reviewed_sha256") == row["source_sha256"]:
            paths["reviewed_current"].append(relative)
        else:
            paths["stale"].append(relative)
    for relative in saved.keys() - live.keys():
        paths["missing_source"].append(relative)
    for relative in coverage:
        if relative not in live or live[relative]["scope"] != "included":
            paths["orphan_review"].append(relative)
    return {"counts": {name: len(items) for name, items in paths.items()}, "paths": paths}


def _source_labels(root: Path, inventory: dict[str, dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    labels: dict[str, list[dict[str, Any]]] = {}
    for relative, row in inventory.items():
        if row["scope"] != "included":
            continue
        path = _guard_file(root, relative)
        if not path.is_file():
            continue
        before = path.stat(follow_symlinks=False)
        source = path.read_bytes()
        after = path.stat(follow_symlinks=False)
        identity = lambda stat: (stat.st_ino, stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns)
        if identity(before) != identity(after):
            raise AuditError(f"source changed during label scan: {relative}")
        if hashlib.sha256(source).hexdigest() != row["source_sha256"]:
            raise AuditError(f"source changed after inventory scan: {relative}")
        for line_number, line in enumerate(source.decode("utf-8", errors="replace").splitlines(), 1):
            match = LABEL.match(line)
            if match:
                labels.setdefault(match["id"], []).append({
                    "kind": match["kind"], "anchor_path": relative,
                    "anchor_line": line_number,
                })
    return labels


def issue_violations(
    root: Path, data: Path, inventory: dict[str, dict[str, Any]] | None = None
) -> list[str]:
    inventory = inventory if inventory is not None else scan_inventory(root, data)
    labels = _source_labels(root, inventory)
    issues = _read_shards(data / "issues", "id")
    violations: list[str] = []
    for issue_id, issue in issues.items():
        if not ISSUE_ID.fullmatch(issue_id):
            violations.append(f"invalid issue ID: {issue_id}")
        if issue.get("kind") not in ("TODO", "BUG"):
            violations.append(f"invalid issue kind: {issue_id}")
        if issue.get("state") not in ("open", "resolved"):
            violations.append(f"invalid issue state: {issue_id}")
        for field in ("path", "anchor_path", "evidence", "impact_or_question", "next_action"):
            if not isinstance(issue.get(field), str) or not issue[field].strip():
                violations.append(f"missing {field}: {issue_id}")
        if issue.get("state") == "resolved":
            if issue_id in labels:
                violations.append(f"resolved issue retains source label: {issue_id}")
            continue
        matches = labels.get(issue_id, [])
        if len(matches) != 1:
            violations.append(f"open issue requires one source label: {issue_id}, found {len(matches)}")
            continue
        label = matches[0]
        if label["kind"] != issue.get("kind") or label["anchor_path"] != issue.get("anchor_path"):
            violations.append(f"source label differs from issue kind or anchor: {issue_id}")
        if issue.get("anchor_line") is not None and issue["anchor_line"] != label["anchor_line"]:
            violations.append(f"source label line differs from issue anchor: {issue_id}")
        target = issue.get("path")
        if isinstance(target, str) and (
            target not in inventory or inventory[target]["scope"] != "included"
        ):
            violations.append(f"issue target is not included in source inventory: {issue_id}")
    for issue_id, matches in labels.items():
        if issue_id not in issues:
            violations.append(f"source label has no issue record: {issue_id}")
        if len(matches) > 1:
            violations.append(f"duplicate source label: {issue_id}")
    return violations


def verify_command(root: Path, data: Path, *, complete: bool) -> int:
    live = scan_inventory(root, data)
    violations = issue_violations(root, data, live)
    status = review_status(root, data, live)
    if complete:
        for name in (
            "unreviewed", "stale", "missing_source", "new_source", "unclassified",
            "new_excluded", "scope_changed", "orphan_review", "inventory_drift",
        ):
            if status["counts"][name]:
                violations.append(f"{name}: {status['counts'][name]}")
    print(json.dumps({"ok": not violations, "violations": violations, "counts": status["counts"]}, ensure_ascii=False))
    return 1 if violations else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--data-dir", type=Path)
    commands = parser.add_subparsers(dest="command", required=True)
    inventory = commands.add_parser("inventory", help="Write or check the Git-visible source inventory")
    inventory_action = inventory.add_mutually_exclusive_group(required=True)
    inventory_action.add_argument("--write", action="store_true")
    inventory_action.add_argument("--check", action="store_true")
    mark = commands.add_parser("mark", help="Record a completed review of current file bytes")
    mark.add_argument("--owner", required=True)
    mark.add_argument("--path", required=True)
    mark.add_argument("--evidence-ref", required=True)
    mark.add_argument("--disposition", required=True, choices=sorted(DISPOSITIONS))
    mark.add_argument("--reviewer")
    mark_batch = commands.add_parser("mark-batch", help="Atomically record one owner's reviewed files")
    mark_batch.add_argument("--owner", required=True)
    mark_batch.add_argument("--input-file", type=Path, required=True)
    mark_batch.add_argument("--reviewer")
    status = commands.add_parser("status", help="Compare reviews with the live source inventory")
    status.add_argument("--json", action="store_true")
    verify = commands.add_parser("verify", help="Check CR labels and optional full coverage")
    verify.add_argument("--complete", action="store_true")
    arguments = parser.parse_args(argv)
    root = arguments.repo_root.resolve()
    data = (arguments.data_dir or root / DEFAULT_DATA).resolve()
    try:
        if arguments.command == "inventory":
            return inventory_command(root, data, write=arguments.write)
        if arguments.command == "mark":
            return mark_command(root, data, arguments)
        if arguments.command == "mark-batch":
            return mark_batch_command(root, data, arguments)
        if arguments.command == "status":
            result = review_status(root, data)
            if arguments.json:
                print(json.dumps(result, ensure_ascii=False))
            else:
                print(" ".join(f"{key}={count}" for key, count in result["counts"].items()))
            return 0
        return verify_command(root, data, complete=arguments.complete)
    except (AuditError, OSError, subprocess.CalledProcessError) as error:
        print(f"source comment audit: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())

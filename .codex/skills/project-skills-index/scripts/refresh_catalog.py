#!/usr/bin/env python3
"""Refresh the Codex project skill catalog from canonical discovery entries."""

from __future__ import annotations

import argparse
from pathlib import Path, PurePosixPath
import re

import yaml

CATALOG = ".codex/skills/project-skills-index/catalog-existing-skills/current-project-skills.md"


def checked_path(root: Path, relative: str) -> Path:
    part = PurePosixPath(relative)
    if part.is_absolute() or not part.parts or any(p in ("..", ".") or ":" in p or "\\" in p for p in part.parts):
        raise ValueError(f"Unsafe generated path: {relative}")
    target = root.joinpath(*part.parts)
    for parent in (target, *target.parents):
        if parent.is_symlink() or (hasattr(parent, "is_junction") and parent.is_junction()):
            raise ValueError(f"Linked path: {parent}")
        if parent == root:
            break
    if not target.resolve().is_relative_to(root.resolve()):
        raise ValueError(f"Path outside root: {target}")
    return target


def render_catalog(repo: Path) -> bytes:
    source = checked_path(repo, ".codex/skills")
    rows = []
    names = set()
    for skill in sorted(source.rglob("SKILL.md")):
        checked_path(repo, skill.relative_to(repo).as_posix())
        text = skill.read_text(encoding="utf-8-sig")
        match = re.match(r"\A---\n(.*?)\n---(?:\n|$)", text, re.S)
        metadata = yaml.safe_load(match[1]) if match else None
        if not isinstance(metadata, dict):
            raise ValueError(f"Invalid skill metadata: {skill}")
        name, description = metadata.get("name"), metadata.get("description")
        if not isinstance(name, str) or len(name) > 64 or not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
            raise ValueError(f"Invalid skill name: {skill}")
        if name in names or not isinstance(description, str) or not description.strip():
            raise ValueError(f"Duplicate name or missing description: {skill}")
        names.add(name)
        relative = skill.relative_to(source).as_posix()
        desc = " ".join(description.split()).replace("|", "\\|")
        rows.append(f"| {chr(96)}{name}{chr(96)} | [SKILL.md](<../../{relative}>) | {desc} |")
    if not rows:
        raise ValueError("No canonical skills found")
    return ("# Project Skills Catalog\n\n"
            "<!-- Generated by refresh_catalog.py; edit canonical SKILL.md frontmatter. -->\n\n"
            f"{len(rows)} discoverable Codex skills. Category indexes and supporting guides use ordinary Markdown; "
            "read them only for the current operation.\n\n"
            "| Skill | Canonical entry | When to use |\n| --- | --- | --- |\n"
            + "\n".join(rows) + "\n").encode("utf-8")


def refresh(repo: Path, write: bool = False) -> list[str]:
    repo = repo.absolute()
    content = render_catalog(repo)
    destination = checked_path(repo, CATALOG)
    if destination.exists() and destination.read_bytes() == content:
        return []
    if write:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(content)
    return [CATALOG]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[4])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="Regenerate the Codex catalog")
    mode.add_argument("--check", action="store_true", help="Read-only drift check (default)")
    args = parser.parse_args()
    try:
        changes = refresh(args.repo_root, args.write)
    except (OSError, ValueError, yaml.YAMLError) as error:
        parser.exit(2, f"Skill catalog refresh failed: {error}\n")
    print(f"{'Updated' if args.write else 'Drift'}: {len(changes)} file(s)")
    if changes and not args.write:
        print("\n".join(changes))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

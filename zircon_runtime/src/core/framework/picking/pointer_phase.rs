//! 定义指针交互的阶段分类值。
//!
//! [`PointerPhase`] 只携带开始、移动、结束或取消的标签；交互状态的存储、转换验证
//! 与资源收尾由使用这些值的代码负责。
/// 表示指针交互处于开始、移动、正常结束或取消阶段的值标签。
///
/// 四个变体均不携带指针身份、位置或按钮数据；使用它的接口须另外保存所需上下文。
/// 此类型可按值复制、比较和作为键，排序按变体的声明顺序进行。
///
/// # 使用时机与生命周期
///
/// 在需要单独传递阶段分类时选择相应变体。枚举不保存当前阶段，也不校验前后阶段关系；
/// 选择结束或取消标签本身不会改变交互状态或执行资源清理。
///
/// # 参考
///
/// 参见 [`Self::Started`]、[`Self::Moved`]、[`Self::Ended`] 和 [`Self::Cancelled`]。
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum PointerPhase {
    /// 标记指针交互的开始阶段。
    ///
    /// 此值只提供开始分类；相关指针身份和交互状态由使用该值的代码管理。
    /// 持有标签不表示已建立捕获或按钮状态。
    ///
    /// # 参考
    ///
    /// 结束分类见 [`PointerPhase::Ended`] 和 [`PointerPhase::Cancelled`]。
    Started,
    /// 标记指针交互的移动阶段。
    ///
    /// 标签没有位置、位移或时间数据，也不记录是否此前出现过开始标签；
    /// 需要这些信息的使用方负责保留相应上下文。
    ///
    /// # 参考
    ///
    /// 开始分类见 [`PointerPhase::Started`]。
    Moved,
    /// 标记指针交互的正常结束阶段。
    ///
    /// 标签描述结束分类；实际按钮释放、状态移除或资源收尾由使用它的代码执行。
    /// 复制或丢弃该值不会完成这些操作。
    ///
    /// # 参考
    ///
    /// 取消分类见 [`PointerPhase::Cancelled`]。
    Ended,
    /// 标记指针交互的取消阶段。
    ///
    /// 此值只表达取消分类；相关状态的清除和资源的释放仍由使用它的代码执行。
    /// 持有标签不能证明取消操作已经完成。
    ///
    /// # 参考
    ///
    /// 正常结束分类见 [`PointerPhase::Ended`]。
    Cancelled,
}

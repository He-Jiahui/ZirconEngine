//! 定义拾取输入、命中与交互状态共同使用的数值指针键。
//!
//! [`PointerId`] 按值携带调用方选定的身份，供位置、射线和命中记录关联同一指针；
//! 编号选择及按该键保存的交互状态生命周期由输入方和状态拥有者管理。
/// 拾取管线用于关联同一指针的位置、射线、命中和交互状态的数值标识。
///
/// 私有 `u64` 字段原样保存调用方提供的数值；相等、散列和排序均依据该数值。
/// 类型接受完整 `u64` 值域，默认标识的原始值为 `0`，未规定无效哨兵或编号分配规则。
///
/// # 身份与生命周期
///
/// 在同一 [`super::PickingEventState`] 或命中集合中，相同原始值表示同一指针键。
/// 调用方应区分需要独立处理的指针，在同一交互期间保持数值一致，并在复用给另一个交互时
/// 处理原有的悬停及按钮状态。标识可复制；丢弃任一副本不会清理按此键保存的状态。
///
/// 视口位置由 [`super::PointerLocation`] 保存，相机和视口的射线维度由 [`super::RayId`] 保存；
/// 这些维度不包含在本标识的数值中。
///
/// # 参考
///
/// 构造和读取原始值分别见 [`Self::new`] 与 [`Self::raw`]。
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct PointerId(u64);

impl PointerId {
    /// 将调用方选定的原始数值封装为拾取指针标识。
    ///
    /// # 参数
    ///
    /// - `raw`：输入方用于关联同一指针的数值键，按值传入；完整 `u64` 值域会原样保存。
    ///   需要区分的指针在同一拾取状态集合内应由调用方选择不同数值。
    ///
    /// # 返回值
    ///
    /// 返回保存相同 `raw` 的标识；传入相同数值会得到相等的标识。
    /// 构造只完成值封装，不登记指针，也不验证数值对应的设备或交互状态。
    ///
    /// # 调用时机与生命周期
    ///
    /// 可在常量定义或准备拾取输入时使用。一次交互内须保持身份数值一致；
    /// 给另一交互复用数值时，由调用方处理 [`super::PickingEventState`] 中的旧状态。
    /// 返回值拥有标量且可复制，构造不会建立或清理这些外部状态。
    ///
    /// # 参考
    ///
    /// 读取保存的数值见 [`Self::raw`]。
    pub const fn new(raw: u64) -> Self {
        Self(raw)
    }

    /// 读取标识中原样保存的数值，供观察或比较拾取指针键时使用。
    ///
    /// # 参数
    ///
    /// - `self`：要读取的标识，按值传入。标识实现 `Copy`，调用后原变量仍可使用。
    ///
    /// # 返回值
    ///
    /// 返回最初传给 [`Self::new`] 的 `u64`；默认构造的标识返回 `0`。
    /// 结果只反映保存的数值，不能证明对应指针已注册、仍在活动或具有全局唯一身份。
    ///
    /// # 调用时机与生命周期
    ///
    /// 持有标识时即可读取，亦可用于常量求值。函数复制数值，不使其它副本失效，
    /// 也不修改按此键保存的位置、悬停或按钮状态；相关状态仍由其拥有者维护。
    ///
    /// # 参考
    ///
    /// 从数值形成标识见 [`Self::new`]。
    pub const fn raw(self) -> u64 {
        self.0
    }
}

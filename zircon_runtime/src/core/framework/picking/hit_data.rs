//! 为拾取后端与编辑器适配层定义可按值传递的命中数据。
//!
//! [`HitData`] 由生成方写入相机标识、排序深度和可选几何数据，再由
//! [`super::HitRecord`] 绑定目标。合并排序由 [`super::sorted_hits_for_pointer`]
//! 执行；悬停和事件快照分别由 [`super::PickingHoverMap`] 与
//! [`super::PickingEventState`] 管理。
//!
//! 本模块只保存输入，不验证相机身份、深度单位、坐标空间或两个可选字段的组合。
//! 解释这些数据时应遵循生成方的约定；被事件状态保留的值可能来自先前帧。
use crate::core::framework::scene::EntityId;
use crate::core::math::{Real, Vec3};

#[derive(Clone, Debug, PartialEq)]
/// 后端提供的命中空间数据；深度参与统一排序，位置和法线可缺省以容纳屏幕空间候选。
///
/// 与 [`super::HitRecord`] 的目标身份一起描述一次命中，供排序、悬停和指针事件使用。
///
/// # 数据约定
/// [`Self::camera`] 与 [`Self::depth`] 按生成方的身份和排序约定解释；深度不具有统一的物理单位。
/// [`Self::position`] 与 [`Self::normal`] 独立可选，任何一种有无组合都可保存，构造时不验证配对关系。
///
/// # 所有权与生命周期
/// 实例拥有字段值，不借用或保活相机、场景与后端资源。可通过 [`Clone`] 显式克隆，
/// 并随命中记录进入悬停快照或事件；类型没有实现 `Copy`。
/// [`super::PickingEventState`] 可保存按压或拖拽命中供后续帧使用，因此收到该值并不证明
/// 当前帧仍有同样的命中，也不证明相机仍然有效。
///
/// # 构造边界
/// [`Self::new`] 原样保存四个参数；公开字段也允许直接构造和修改。
/// 身份有效性、几何一致性和深度解释由生成方与使用方约定。
pub struct HitData {
    /// 生成方记录的相机标识，随该次命中数据一起传递。
    ///
    /// 射线后端写入 [`super::RayId::camera`]；编辑器视口适配层使用占位值 `0`。
    /// 此字段不校验或保活相机实体；需要查询相机的调用者应先按生成方约定判断并验证标识。
    pub camera: EntityId,
    /// 生成方提供的排序键，其物理意义和单位由生成方约定。
    ///
    /// [`super::sorted_hits_for_pointer`] 先按目标优先级升序、
    /// [`super::PointerHits::order`] 降序排列，再用 `total_cmp` 按本字段升序比较；
    /// 前述键相同后，按来源批次索引和批次内命中索引升序打破平局。
    /// 球形射线后端以射线参数作为深度，编辑器视口适配层则组合量化屏幕得分和投影深度。
    /// 构造函数不检查有限性、正负或单位；需要可比较的结果时，生成方须提供相容的排序约定。
    pub depth: Real,
    /// 生成方提供的可选三维命中位置。
    ///
    /// `Some` 的坐标空间由生成方定义；球形射线后端采用 [`super::PointerRay`] 的空间，
    /// 以射线原点、方向和深度计算位置。`None` 仅表示未提供位置，不能据此判定后端类别。
    /// 本字段与 [`Self::normal`] 独立可选；使用几何数据前应分别处理缺省并核对空间约定。
    pub position: Option<Vec3>,
    /// 生成方提供的可选命中表面法线。
    ///
    /// `Some` 的坐标空间与方向约定由生成方定义；球形射线后端从球心指向命中点的方向
    /// 经 `normalize_or_zero` 计算为单位向量或零向量。类型与 [`Self::new`] 不检查长度或归一化状态。
    /// `None` 仅表示未提供法线，与 [`Self::position`] 的有无相互独立；使用前须分别检查可用性。
    pub normal: Option<Vec3>,
}

impl HitData {
    /// 原样保存生成方提供的相机标识、排序深度和可选几何数据，创建一个 [`Self`] 值。
    ///
    /// # 参数
    /// - `camera`：生成方的相机标识；射线后端通常传入 [`super::RayId::camera`]，
    ///   编辑器视口适配层使用 `0`。函数不验证该实体是否存在。
    /// - `depth`：用于统一排序的键。物理意义和单位由生成方约定，比较顺序见 [`Self::depth`]。
    /// - `position`：可选的三维命中位置，按生成方坐标空间解释；未提供时传 `None`。
    /// - `normal`：可选的命中法线，按生成方的空间和方向约定解释；与 `position` 独立可选。
    ///
    /// # 返回
    /// 返回拥有全部参数值的命中数据；不执行拾取、实体查询、有限性检查、归一化或字段配对校验。
    /// 返回值可交给 [`super::HitRecord::new`] 绑定目标，再进入排序、悬停或事件状态。
    ///
    /// # 所有权与生命周期
    /// 结果不借用相机、场景或后端资源。调用不修改外部状态，也不排队或启动异步工作；
    /// 后续保存或克隆该值不会自动刷新命中，使用历史事件数据时仍需由调用方判断时效性。
    ///
    /// # 参考
    /// 参见 [`Self`]、[`Self::depth`] 与 [`super::HitRecord::new`]。
    pub fn new(
        camera: EntityId,
        depth: Real,
        position: Option<Vec3>,
        normal: Option<Vec3>,
    ) -> Self {
        Self {
            camera,
            depth,
            position,
            normal,
        }
    }
}

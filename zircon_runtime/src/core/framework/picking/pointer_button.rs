//! 定义拾取输入与交互事件共同使用的按钮及接触分类。
//!
//! [`PointerButton`] 随 [`super::PointerAction`] 和 [`super::PickingEventKind`] 按值传递；
//! 输入来源负责分类映射，事件状态负责按指针与按钮组合维护交互内容。
/// 为拾取输入和派生交互事件标记按钮或接触的分类。
///
/// [`super::PointerAction`] 用该值标记按下与释放，点击和拖拽等 [`super::PickingEventKind`]
/// 继续保留分类，使同一指针的按钮交互能够对应。分类不包含指针身份或是否按下的状态。
///
/// # 键与使用约束
///
/// [`super::PickingEventState`] 以 [`super::PointerId`] 和本值的组合索引按钮内容。
/// 同一次按钮交互的按下与释放应使用一致分类；不同指针可以使用相同分类而分别保存状态。
/// 相等和散列区分变体，附加编码见 [`Self::Other`]；排序按变体声明顺序，
/// 两个 `Other` 再按其 `u16` 编码排序。输入方负责分类与来源操作之间的映射。
///
/// # 所有权与生命周期
///
/// 分类可按值复制，不持有设备或交互资源。保存、复制或丢弃分类不会推进按钮状态；
/// 按下、释放及指针取消的处理由输入动作和事件状态共同完成。
///
/// # 参考
///
/// 参见 [`super::PointerAction`]、[`super::PickingEventKind`] 和 [`super::PickingEventState`]。
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum PointerButton {
    /// 输入来源认定的主操作按钮分类。
    ///
    /// 在主按钮的按下与释放动作中保持该分类一致，使状态表对应同一指针的交互内容。
    /// 值本身不记录是否按下；它与物理按钮之间的映射由输入来源确定。
    ///
    /// # 参考
    ///
    /// 动作和状态维护见 [`super::PointerAction`] 与 [`super::PickingEventState`]。
    Primary,
    /// 输入来源认定的次操作按钮分类。
    ///
    /// 同一指针下，此分类与 [`PointerButton::Primary`] 使用不同按钮键。
    /// 使用它时，输入来源须在对应的按下与释放期间保持分类一致；标签不拥有按钮状态。
    ///
    /// # 参考
    ///
    /// 按下和释放的承载接口见 [`super::PointerAction`]。
    Secondary,
    /// 输入来源认定的中间按钮分类。
    ///
    /// 用于标记该按钮的按下与释放，值中不含滚动方向或位移。
    /// 输入来源负责选择分类并保持成对动作一致；复制标签不会改变交互内容。
    ///
    /// # 参考
    ///
    /// 按钮动作与独立的滚动动作均由 [`super::PointerAction`] 表达。
    Middle,
    /// 在将触摸接触表达为按钮动作的拾取输入中标记接触分类。
    ///
    /// 触点所属的指针仍由 [`super::PointerId`] 区分；多个指针使用此分类时，
    /// 状态表按指针分别保存交互内容。标签不保存接触是否持续，也不拥有触点资源。
    ///
    /// # 参考
    ///
    /// 接触的按下和释放由 [`super::PointerAction`] 承载。
    TouchContact,
    /// 在将笔接触表达为按钮动作的拾取输入中标记接触分类。
    ///
    /// 此值与 [`PointerButton::TouchContact`] 为不同按钮键；具体指针由 [`super::PointerId`] 区分。
    /// 标签不携带位置或压力数据，输入来源负责分类及按下、释放期间的一致性。
    ///
    /// # 参考
    ///
    /// 接触动作由 [`super::PointerAction`] 表达，状态存储在相应指针的交互内容中。
    PenContact,
    /// 保存具名按钮或接触分类以外的附加按钮编码。
    ///
    /// 内嵌 `u16` 是输入来源选定的分类数值，按值拥有且允许完整 `u16` 值域。
    /// 同一指针下，相同编码表示同一 `Other` 按钮键，不同编码分别保存交互内容。
    /// 类型没有规定编码与某个平台按钮编号的对应关系；输入方负责码义和成对动作的一致性。
    ///
    /// # 所有权与生命周期
    ///
    /// 编码随分类复制，不借用输入来源或持有资源；保存或丢弃值不会推进按钮状态。
    ///
    /// # 参考
    ///
    /// 动作与状态索引见 [`super::PointerAction`] 和 [`super::PickingEventState`]。
    Other(u16),
}

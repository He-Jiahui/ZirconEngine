//! 定义物理查询结果的数量与排序策略，不保存命中或查询状态。
//!
//! 当前共享实现以遍历顺序处理 First，以查询种类提供的比较度量处理 Closest 和 All。
//! 选择模式不会同步世界，也不改变 provider 对几何形状的支持范围。
use serde::{Deserialize, Serialize};

/// 控制结果数量与顺序：首个依遍历顺序，最近依查询度量，全部按度量排序。
///
/// # 使用时机与度量
///
/// 在构造射线、扫掠或重叠请求时选择结果策略；默认值为 [`Self::Closest`]。
/// 当前 manager 的射线与扫掠按命中距离比较，重叠按目标中心到查询中心的平方距离比较；
/// 相同度量再按实体 ID 比较。最近重叠目标不代表最小穿透深度或最接近的表面接触点。
///
/// # 生命周期与约束
///
/// 本值可复制和序列化，只描述一次请求的策略；`First` 不承诺最近结果，
/// `All` 表示当前实现实际生成的全部候选，不表示所有几何类型都受支持或每个实体仅有一个命中。
///
/// # 参考
///
/// [`super::PhysicsRayCastQuery`]、[`super::PhysicsShapeCastQuery`]、[`super::PhysicsShapeOverlapQuery`]。
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum PhysicsQueryMode {
    /// 只取遍历中首个通过筛选并产生几何命中的候选；共享实现取得它后停止继续生成候选。
    /// 适合任意命中即可的检查，结果随碰撞体遍历次序变化，不保证距离最近。
    First,
    /// 按本类查询的度量取最小候选，最多返回一个；它也是构造与缺省反序列化模式的默认值。
    /// 当前重叠查询比较中心距离，射线和扫掠比较命中距离，同距再比较实体 ID。
    #[default]
    Closest,
    /// 收集本实现产生的全部合格候选并按查询度量排序，空集合仍是有效的查询结果形态。
    /// 调用者需要全部候选时使用；排序不消除重复实体或补齐当前不支持的几何。
    All,
}

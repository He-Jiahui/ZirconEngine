//! 定义共享动作服务的映射访问和帧求值接口。
//!
//! # 责任
//!
//! 调用方提供已取得的输入帧；如需排除上层已经处理的输入，负责向相应入口提供消费列表。实现者维护映射读取、替换和求值之间的一致视图。所有方法均由实现者提供。
//!
//! # 约束
//!
//! 接口要求 Send + Sync；锁类型、锁中毒处理、编译缓存和工作区复用属于具体实现选择。
//!
//! # 使用时机与生命周期
//!
//! 帧、上下文名和消费列表只作为调用期间的借入值；返回映射及状态拥有数据，后续配置变更不会改写已有返回值。服务注册和注册身份的有效期由外层 Core 服务接口管理。
//!
//! # 参考
//!
//! [`InputActionManager`]、[`InputActionMap`]、[`InputActionState`]、[`InputFrameSnapshot`]。
use super::{GamepadAxisInput, InputActionMap, InputActionState, InputButton, InputFrameSnapshot};

/// 将物理帧快照求值为命名动作的服务边界；映射修改与求值由实现保持一致视图。
/// 调用方可先按 UI 或更高层路由结果标记已消费按钮、轴，再求值剩余输入。
/// 提供可共享调用的命名动作服务契约。
///
/// # 责任
///
/// 调用方组织帧和消费列表，修改取得的映射后显式安装；实现者为读取、替换及求值提供一致的映射视图，并实现全部方法。
///
/// # 约束
///
/// Send + Sync 约束共享使用的线程安全能力，接口没有规定互斥锁或中毒恢复策略，也没有 Result 错误通道。默认运行时实现串行访问求值器；其他实现需自行满足接口语义。
///
/// # 使用时机与生命周期
///
/// 一次求值读取提供的帧，接口本身不采集宿主事件或推进输入帧。返回的 InputActionState 保存该次结果，不会随管理器下一次求值自动更新。
///
/// # 参考
///
/// [`InputActionMap`]、[`InputActionState`]、[`Self::action_map()`]、[`Self::set_action_map()`]、[`Self::evaluate_actions()`]。
pub trait InputActionManager: Send + Sync {
    /// 取得当前映射的拥有型配置副本。
    ///
    /// # 参数
    ///
    /// - `self`：共享借用动作服务。
    ///
    /// # 返回
    ///
    /// 返回 InputActionMap；调用方可以独立保存和修改它，修改须通过 set_action_map 才安装到服务。
    ///
    /// # 使用时机与生命周期
    ///
    /// 用于查看配置或准备重绑定。返回值不借用服务；随后替换映射不会改写已有副本。默认运行时实现锁住求值器后克隆映射。
    ///
    /// # 参考
    ///
    /// [`InputActionMap`]、[`Self::set_action_map()`]。
    fn action_map(&self) -> InputActionMap;
    /// 接收并安装后续求值使用的动作映射。
    ///
    /// # 参数
    ///
    /// - `self`：共享借用动作服务；实现者负责协调配置写入与求值。
    /// - `action_map`：转交服务的拥有型配置；调用方负责构造符合用途的动作和绑定。
    ///
    /// # 返回
    ///
    /// 返回 ()；正常返回后，所安装映射供后续求值使用，直到再次替换。接口不提供配置校验或错误返回。
    ///
    /// # 使用时机与生命周期
    ///
    /// 重绑定时调用。默认运行时实现重建编译代际，再替换映射并清空旧工作区的逻辑内容，保留可复用容量；它直接编译传入配置，不替调用方清理已有空绑定。已返回的状态或映射副本继续独立存在。
    ///
    /// # 参考
    ///
    /// [`InputActionMap`]、[`Self::action_map()`]、[`Self::evaluate_actions()`]。
    fn set_action_map(&self, action_map: InputActionMap);
    /// 对提供的帧按当前映射求值，不传入消费列表或活动上下文筛选。
    ///
    /// # 参数
    ///
    /// - `self`：共享借用动作服务。
    /// - `frame`：本次只读输入帧；调用方负责帧状态和边沿窗口的一致性，求值不推进该窗口。
    ///
    /// # 返回
    ///
    /// 返回本次命名动作的拥有型 InputActionState，包含按住、激活/停用边沿和数值；不借用帧、切片或服务。
    ///
    /// # 约束
    ///
    /// 默认运行时实现按全部启用上下文求值，保留无上下文动作。这些过滤不回写帧或永久修改映射；其他实现负责提供相同入口约定，具体求值和同步机制由实现者选择。
    ///
    /// # 使用时机与生命周期
    ///
    /// 在取得本次输入帧后调用；默认运行时实现不会在本入口自动读取上层消费记录。需要消费过滤时，调用方应选择接收消费列表的入口并显式传入列表。输入帧只在调用期间借用；返回状态可在这些借用结束后保存。随后求值、工作区复用或映射替换不会回写该状态。
    ///
    /// # 参考
    ///
    /// [`InputFrameSnapshot`]、[`InputActionState`]、[`Self::set_action_map()`]。
    fn evaluate_actions(&self, frame: &InputFrameSnapshot) -> InputActionState;
    /// 对提供的帧求值，并排除调用方已消费的按钮。
    ///
    /// # 参数
    ///
    /// - `self`：共享借用动作服务。
    /// - `frame`：本次只读输入帧；调用方负责帧状态和边沿窗口的一致性，求值不推进该窗口。
    /// - `consumed_buttons`：上层已处理的完整按钮身份列表；求值不修改该切片。
    ///
    /// # 返回
    ///
    /// 返回本次命名动作的拥有型 InputActionState，包含按住、激活/停用边沿和数值；不借用帧、切片或服务。
    ///
    /// # 约束
    ///
    /// 默认运行时实现按全部启用上下文求值，保留无上下文动作；绑定任一所需按钮被消费时，整条绑定跳过。这些过滤不回写帧或永久修改映射；其他实现负责提供相同入口约定，具体求值和同步机制由实现者选择。
    ///
    /// # 使用时机与生命周期
    ///
    /// 在取得本次输入帧、整理需要排除的消费列表后调用；列表由本次参数显式提供，可来自 UI 或其他上层路由。输入帧和按钮消费列表只在调用期间借用；返回状态可在这些借用结束后保存。随后求值、工作区复用或映射替换不会回写该状态。
    ///
    /// # 参考
    ///
    /// [`InputFrameSnapshot`]、[`InputActionState`]、[`Self::set_action_map()`]、[`InputButton`]。
    fn evaluate_actions_with_consumed_buttons(
        &self,
        frame: &InputFrameSnapshot,
        consumed_buttons: &[InputButton],
    ) -> InputActionState;
    /// 对提供的帧求值，并应用已消费按钮和手柄轴的选择。
    ///
    /// # 参数
    ///
    /// - `self`：共享借用动作服务。
    /// - `frame`：本次只读输入帧；调用方负责帧状态和边沿窗口的一致性，求值不推进该窗口。
    /// - `consumed_buttons`：上层已处理的完整按钮身份列表；求值不修改该切片。
    /// - `consumed_axes`：上层已处理的设备与轴组合身份列表；同名轴属于不同设备时是不同项。
    ///
    /// # 返回
    ///
    /// 返回本次命名动作的拥有型 InputActionState，包含按住、激活/停用边沿和数值；不借用帧、切片或服务。
    ///
    /// # 约束
    ///
    /// 默认运行时实现按全部启用上下文求值，保留无上下文动作；绑定任一所需按钮被消费时，整条绑定跳过；被消费的轴源单独跳过，其他轴源仍可贡献该绑定。这些过滤不回写帧或永久修改映射；其他实现负责提供相同入口约定，具体求值和同步机制由实现者选择。
    ///
    /// # 使用时机与生命周期
    ///
    /// 在取得本次输入帧、整理需要排除的消费列表后调用；列表由本次参数显式提供，可来自 UI 或其他上层路由。输入帧、按钮消费列表和轴消费列表只在调用期间借用；返回状态可在这些借用结束后保存。随后求值、工作区复用或映射替换不会回写该状态。
    ///
    /// # 参考
    ///
    /// [`InputFrameSnapshot`]、[`InputActionState`]、[`Self::set_action_map()`]、[`InputButton`]、[`GamepadAxisInput`]。
    fn evaluate_actions_with_consumed_input(
        &self,
        frame: &InputFrameSnapshot,
        consumed_buttons: &[InputButton],
        consumed_axes: &[GamepadAxisInput],
    ) -> InputActionState;
    /// 按本次活动上下文对提供的帧求值。
    ///
    /// # 参数
    ///
    /// - `self`：共享借用动作服务。
    /// - `frame`：本次只读输入帧；调用方负责帧状态和边沿窗口的一致性，求值不推进该窗口。
    /// - `active_contexts`：只对本次求值生效的上下文名称切片；空列表表示全部启用上下文。
    ///
    /// # 返回
    ///
    /// 返回本次命名动作的拥有型 InputActionState，包含按住、激活/停用边沿和数值；不借用帧、切片或服务。
    ///
    /// # 约束
    ///
    /// 默认运行时实现保留无上下文动作，忽略未知活动名，重复名称幂等，并继续尊重配置禁用位。这些过滤不回写帧或永久修改映射；其他实现负责提供相同入口约定，具体求值和同步机制由实现者选择。
    ///
    /// # 使用时机与生命周期
    ///
    /// 在取得本次输入帧后调用；默认运行时实现不会在本入口自动读取上层消费记录。需要消费过滤时，调用方应选择接收消费列表的入口并显式传入列表。输入帧、活动上下文名称切片及其中的字符串只在调用期间借用；返回状态可在这些借用结束后保存。随后求值、工作区复用或映射替换不会回写该状态。
    ///
    /// # 参考
    ///
    /// [`InputFrameSnapshot`]、[`InputActionState`]、[`Self::set_action_map()`]、[`Self::evaluate_actions()`]。
    fn evaluate_actions_with_active_contexts(
        &self,
        frame: &InputFrameSnapshot,
        active_contexts: &[&str],
    ) -> InputActionState;
    /// 同时应用本次活动上下文和已消费按钮选择。
    ///
    /// # 参数
    ///
    /// - `self`：共享借用动作服务。
    /// - `frame`：本次只读输入帧；调用方负责帧状态和边沿窗口的一致性，求值不推进该窗口。
    /// - `active_contexts`：只对本次求值生效的上下文名称切片；空列表表示全部启用上下文。
    /// - `consumed_buttons`：上层已处理的完整按钮身份列表；求值不修改该切片。
    ///
    /// # 返回
    ///
    /// 返回本次命名动作的拥有型 InputActionState，包含按住、激活/停用边沿和数值；不借用帧、切片或服务。
    ///
    /// # 约束
    ///
    /// 默认运行时实现保留无上下文动作，忽略未知活动名，重复名称幂等，并继续尊重配置禁用位；绑定任一所需按钮被消费时，整条绑定跳过。这些过滤不回写帧或永久修改映射；其他实现负责提供相同入口约定，具体求值和同步机制由实现者选择。
    ///
    /// # 使用时机与生命周期
    ///
    /// 在取得本次输入帧、整理需要排除的消费列表后调用；列表由本次参数显式提供，可来自 UI 或其他上层路由。输入帧、活动上下文名称切片及其中的字符串、按钮消费列表只在调用期间借用；返回状态可在这些借用结束后保存。随后求值、工作区复用或映射替换不会回写该状态。
    ///
    /// # 参考
    ///
    /// [`InputFrameSnapshot`]、[`InputActionState`]、[`Self::set_action_map()`]、[`Self::evaluate_actions()`]、[`InputButton`]。
    fn evaluate_actions_with_active_contexts_and_consumed_buttons(
        &self,
        frame: &InputFrameSnapshot,
        active_contexts: &[&str],
        consumed_buttons: &[InputButton],
    ) -> InputActionState;
    /// 同时限定本次可用上下文和已消费的物理输入；空上下文列表表示使用全部启用上下文。
    ///
    /// 同时应用本次活动上下文及已消费按钮、手柄轴选择。
    ///
    /// # 参数
    ///
    /// - `self`：共享借用动作服务。
    /// - `frame`：本次只读输入帧；调用方负责帧状态和边沿窗口的一致性，求值不推进该窗口。
    /// - `active_contexts`：只对本次求值生效的上下文名称切片；空列表表示全部启用上下文。
    /// - `consumed_buttons`：上层已处理的完整按钮身份列表；求值不修改该切片。
    /// - `consumed_axes`：上层已处理的设备与轴组合身份列表；同名轴属于不同设备时是不同项。
    ///
    /// # 返回
    ///
    /// 返回本次命名动作的拥有型 InputActionState，包含按住、激活/停用边沿和数值；不借用帧、切片或服务。
    ///
    /// # 约束
    ///
    /// 默认运行时实现保留无上下文动作，忽略未知活动名，重复名称幂等，并继续尊重配置禁用位；绑定任一所需按钮被消费时，整条绑定跳过；被消费的轴源单独跳过，其他轴源仍可贡献该绑定。这些过滤不回写帧或永久修改映射；其他实现负责提供相同入口约定，具体求值和同步机制由实现者选择。
    ///
    /// # 使用时机与生命周期
    ///
    /// 在取得本次输入帧、整理需要排除的消费列表后调用；列表由本次参数显式提供，可来自 UI 或其他上层路由。输入帧、活动上下文名称切片及其中的字符串、按钮消费列表和轴消费列表只在调用期间借用；返回状态可在这些借用结束后保存。随后求值、工作区复用或映射替换不会回写该状态。
    ///
    /// # 参考
    ///
    /// [`InputFrameSnapshot`]、[`InputActionState`]、[`Self::set_action_map()`]、[`Self::evaluate_actions()`]、[`InputButton`]、[`GamepadAxisInput`]。
    fn evaluate_actions_with_active_contexts_and_consumed_input(
        &self,
        frame: &InputFrameSnapshot,
        active_contexts: &[&str],
        consumed_buttons: &[InputButton],
        consumed_axes: &[GamepadAxisInput],
    ) -> InputActionState;
}

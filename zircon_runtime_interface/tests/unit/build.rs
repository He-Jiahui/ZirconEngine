use super::{generate_slot_catalog_from_source, render_trusted_host_build_set};

const CURRENT_INTERFACE_SPEC: &str =
    include_str!("../../src/runtime_build_set/interface_spec_v1.json");

fn interface_spec_with_slots(required: &str, optional: &str, host_optional: &str) -> String {
    format!(
        r#"{{
                "family": "zircon.runtime.internal",
                "spec_version": 1,
                "runtime_api_version": 8,
                "entry_symbol": "zircon_runtime_get_api_v8",
                "runtime_api_required_slots": {required},
                "runtime_api_optional_slots": {optional},
                "host_api_optional_slots": {host_optional}
            }}"#
    )
}

#[test]
fn trusted_host_build_set_renderer_rejects_untrusted_values() {
    assert_eq!(
        render_trusted_host_build_set(None).unwrap(),
        "// @generated by build.rs from the curated cargo-zircon BuildSet environment.\n\npub const ZR_TRUSTED_HOST_BUILD_SET_ID_V1: Option<&str> = None;\n"
    );
    assert!(render_trusted_host_build_set(Some(&"A".repeat(64))).is_err());
    assert!(render_trusted_host_build_set(Some(&"z".repeat(64))).is_err());
    assert!(render_trusted_host_build_set(Some(&"a".repeat(64)))
        .unwrap()
        .contains("Some(\""));
}

#[test]
fn slot_catalog_generator_emits_the_current_interface_inventory() {
    let catalog = generate_slot_catalog_from_source(CURRENT_INTERFACE_SPEC)
        .expect("current InterfaceSpec must generate a Rust slot catalog");

    assert!(catalog.starts_with("// @generated by build.rs"));
    assert!(catalog.contains("pub const ZR_RUNTIME_INTERFACE_FAMILY_V1"));
    assert!(catalog.contains("pub const ZIRCON_RUNTIME_API_VERSION_V8: u32 = 8;"));
    assert!(catalog.contains("pub const ZR_RUNTIME_GET_API_SYMBOL_V8"));
    assert!(catalog.contains("pub const ZR_RUNTIME_API_V8_REQUIRED_SLOT_NAMES"));
    assert!(catalog.contains("pub const ZR_RUNTIME_API_V8_OPTIONAL_SLOT_NAMES"));
    assert!(catalog.contains("pub const ZR_HOST_API_V1_OPTIONAL_SLOT_NAMES"));
    assert!(catalog.contains("\"create_session\""));
    assert!(catalog.contains("\"present_viewport\""));
    assert!(catalog.contains("\"diagnostics_sink\""));
}

#[test]
fn slot_catalog_generator_rejects_duplicate_runtime_slots_across_partitions() {
    let source = interface_spec_with_slots("[\"create_session\"]", "[\"create_session\"]", "[]");
    let error = generate_slot_catalog_from_source(&source)
        .expect_err("a V8 slot cannot be both required and optional");

    assert!(error.contains("runtime_api_optional_slots"));
    assert!(error.contains("create_session"));
}

#[test]
fn slot_catalog_generator_keeps_host_slots_in_a_separate_namespace() {
    let source =
        interface_spec_with_slots("[\"release_allocation\"]", "[]", "[\"release_allocation\"]");
    let catalog = generate_slot_catalog_from_source(&source)
        .expect("host and runtime tables may reuse a field label");

    assert_eq!(catalog.matches("\"release_allocation\"").count(), 2);
}

#[test]
fn slot_catalog_generator_rejects_non_rust_slot_identifiers() {
    let source = interface_spec_with_slots("[\"1bad\"]", "[]", "[]");
    let error = generate_slot_catalog_from_source(&source)
        .expect_err("a generated Rust catalog must reject invalid identifiers");

    assert!(error.contains("runtime_api_required_slots"));
    assert!(error.contains("1bad"));
}

#[test]
fn slot_catalog_generator_rejects_metadata_that_does_not_describe_v8() {
    let source =
        CURRENT_INTERFACE_SPEC.replace("\"runtime_api_version\": 8", "\"runtime_api_version\": 9");
    let error = generate_slot_catalog_from_source(&source)
        .expect_err("the V8 Rust table cannot be generated from a V9 InterfaceSpec");

    assert!(error.contains("runtime_api_version"));
    assert!(error.contains("must be 8"));
}

#[test]
fn retained_model_admission_requires_the_complete_audited_identity() {
    let version = "rustc 1.99.1\ncommit-hash: 58cf8f9c35b355199727627d07ae34a4e2846d67\n";
    let libraries = [
        (
            "liballoc-",
            "1713afb7fc9da7a917293bafdede9562ceddd75700d5a5ff57d4eeb2e42ce9b1",
        ),
        (
            "libcore-",
            "b346ce2305e13b1a5ec9ab6e093028caee38227c540cdaf78d7b253f59ae5913",
        ),
        (
            "libstd-",
            "ea104615e69d068c8a12c749135c7138b3ec28c7275ae163f91169a03561f75b",
        ),
    ]
    .map(|(name, hash)| (name.to_owned(), hash.to_owned()));
    let admit = |target, version: &str, libraries: &[(String, String)], mode| {
        super::admitted_retained_std_model_v1(target, version, libraries, mode)
    };
    assert_eq!(
        admit("x86_64-unknown-linux-gnu", version, &libraries, true),
        Some("ZR_RETAINED_STD_RUST_1_99_1_58CF8F9C_X86_64_LINUX_GNU_GLOBAL_V1")
    );
    assert!(admit("x86_64-pc-windows-msvc", version, &libraries, true).is_none());
    assert!(admit(
        "x86_64-unknown-linux-gnu",
        "commit-hash: unknown",
        &libraries,
        true
    )
    .is_none());
    assert!(admit("x86_64-unknown-linux-gnu", version, &libraries, false).is_none());
    assert!(admit("x86_64-unknown-linux-gnu", version, &libraries[..2], true).is_none());
    for index in 0..libraries.len() {
        let mut changed = libraries.clone();
        changed[index].1.push('0');
        assert!(admit("x86_64-unknown-linux-gnu", version, &changed, true).is_none());
    }
    let mut extra = libraries.to_vec();
    extra.push(libraries[0].clone());
    assert!(admit("x86_64-unknown-linux-gnu", version, &extra, true).is_none());

    let windows = [
        (
            "liballoc-",
            "ec31d2076f0a772502d983a3f08544f419a2e9ec7b91dde39085160a9fcbfe8d",
        ),
        (
            "libcore-",
            "cc07c244f9e8a0bdc3d541de001a0fd90abec28d3a7343c05ec759c7bd89871b",
        ),
        (
            "libstd-",
            "dad1e7dca0365c18af4f6ceb3e8f9362974bc099ef5dc37f4b4c4d8d14b6edd0",
        ),
    ]
    .map(|(name, hash)| (name.to_owned(), hash.to_owned()));
    assert_eq!(
        admit(
            "x86_64-pc-windows-msvc",
            "commit-hash: e408947bfd200af42db322daf0fadfe7e26d3bd1",
            &windows,
            true
        ),
        Some("ZR_RETAINED_STD_RUST_1_94_1_E408947B_X86_64_WINDOWS_MSVC_GLOBAL_V1")
    );
}

import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SOURCE_COMMIT = '5ef9f7cb21cd8875b6d2c49701015dfcd78de35a';
const EXPECTED = [{ x: 7, z: -8 }, { x: 6, z: 294 }, { x: 6, z: 654 }];

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const sourceRoot = resolve(projectRoot, '..', '..', 'dev', 'world-of-claudecraft');
const sourceManifestPath = join(projectRoot, 'reference', 'current-head', 'source_manifest.json');
const extractorPath = join(scriptDirectory, 'm3_mailbox_placement_source_extract.mjs');
const loaderUrl = pathToFileURL(join(scriptDirectory, 'typescript_git_loader.mjs')).href;
const contractPath = join(projectRoot, 'contracts', 'm3_mailbox_placement.json');
const zrPath = join(projectRoot, 'scripts', 'woc_game', 'src', 'generated', 'm3_mailbox_placement.zr');
const checkOnly = process.argv.includes('--check');

main();

function main() {
  execFileSync('git', ['-C', sourceRoot, 'cat-file', '-e', `${SOURCE_COMMIT}^{commit}`]);
  const manifest = JSON.parse(readFileSync(sourceManifestPath, 'utf8'));
  assert(manifest.source_commit === SOURCE_COMMIT, 'WOC source manifest commit drifted');
  const extracted = extract();
  assert(JSON.stringify(extracted.entries) === JSON.stringify(EXPECTED), 'mailbox source positions or order drifted');
  const document = {
    schema_version: 1,
    source_commit: SOURCE_COMMIT,
    generated_by: 'examples/woc/tools/m3_mailbox_placement_codegen.mjs',
    source_identity: gitBlobIdentity('src/sim/content/mailboxes.ts'),
    mailboxes: extracted.entries,
  };
  document.catalog_sha256 = sha256(JSON.stringify({
    source_identity: document.source_identity,
    mailboxes: document.mailboxes,
  }));
  const contract = `${JSON.stringify(document, null, 2)}\n`;
  const zr = render(document);
  writeOrCheck(contractPath, contract, 'm3_mailbox_placement.json');
  writeOrCheck(zrPath, zr, 'm3_mailbox_placement.zr');
  process.stdout.write(`${checkOnly ? 'checked' : 'generated'} ${document.mailboxes.length} mailbox placements ` +
    `(${document.catalog_sha256.slice(0, 15)})\n`);
}

function extract() {
  const child = spawnSync(process.execPath, [
    '--no-warnings', '--experimental-loader', loaderUrl, extractorPath,
  ], {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
    env: { ...process.env, WOC_GIT_ROOT: sourceRoot, WOC_GIT_COMMIT: SOURCE_COMMIT },
  });
  assert(child.status === 0, child.stderr || `mailbox extractor exited ${child.status}`);
  return JSON.parse(child.stdout);
}

function render(document) {
  const lines = [
    '// Generated by examples/woc/tools/m3_mailbox_placement_codegen.mjs.',
    `// Source ${document.source_commit}; constructor-order mailbox positions; do not edit.`,
    '',
    'mailboxIndexIsValid(index: int): bool {',
    `    return index >= 0 && index < ${document.mailboxes.length};`,
    '}',
    '',
    'pub catalogSha(required: bool): string {',
    '    if (!required) { throw "woc mailbox placement catalog is required"; }',
    `    return ${zrString(document.catalog_sha256)};`,
    '}',
    '',
    'pub mailboxCount(required: bool): int {',
    '    if (!required) { throw "woc mailbox placement count is required"; }',
    `    return ${document.mailboxes.length};`,
    '}',
    '',
    'pub rawCoordinate(index: int, axis: int, required: bool): float {',
    '    if (!required || !mailboxIndexIsValid(index) || (axis != 1 && axis != 2)) {',
    '        throw "woc mailbox coordinate is invalid";',
    '    }',
  ];
  document.mailboxes.forEach((entry, index) => lines.push(
    `    if (index == ${index}) { return axis == 1 ? ${zrNumber(entry.x)} : ${zrNumber(entry.z)}; }`,
  ));
  lines.push('    throw "woc mailbox coordinate is invalid";', '}', '', 'pub contractTest(): int {',
    `    if (mailboxCount(true) != ${document.mailboxes.length} ||`,
    `        rawCoordinate(0, 1, true) != ${zrNumber(document.mailboxes[0].x)} ||`,
    `        rawCoordinate(1, 2, true) != ${zrNumber(document.mailboxes[1].z)} ||`,
    `        rawCoordinate(2, 1, true) != ${zrNumber(document.mailboxes[2].x)}) {`,
    '        return -1;',
    '    }',
    '    return 1;',
    '}',
  );
  return `${lines.join('\n')}\n`;
}

function gitBlobIdentity(sourcePath) {
  const sourceText = execFileSync('git', ['-C', sourceRoot, 'show', `${SOURCE_COMMIT}:${sourcePath}`], {
    encoding: 'utf8',
  });
  const blob = execFileSync('git', ['-C', sourceRoot, 'rev-parse', `${SOURCE_COMMIT}:${sourcePath}`], {
    encoding: 'utf8',
  }).trim();
  return { source_path: sourcePath, git_blob: blob, sha256: sha256Text(sourceText) };
}

function writeOrCheck(path, content, name) {
  if (checkOnly) {
    assert(existsSync(path), `${name} is missing; run the mailbox placement generator`);
    assert(readFileSync(path, 'utf8') === content, `${name} is stale; run the mailbox placement generator`);
    return;
  }
  writeFileSync(path, content, 'utf8');
}

function zrString(value) { return JSON.stringify(value); }
function zrNumber(value) {
  assert(Number.isFinite(value), 'mailbox placement contains a non-finite number');
  return String(value);
}
function sha256(value) { return sha256Text(value); }
function sha256Text(value) { return createHash('sha256').update(value).digest('hex'); }
function assert(condition, message) { if (!condition) throw new Error(message); }

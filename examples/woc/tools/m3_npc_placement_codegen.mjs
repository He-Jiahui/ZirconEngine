import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SOURCE_COMMIT = '5ef9f7cb21cd8875b6d2c49701015dfcd78de35a';
const EXPECTED = {
  total: 35,
  static: 31,
  dynamicIds: ['groundskeeper_bram', 'brother_aldric_raid', 'fury', 'spirit_healer'],
  first: { id: 'the_merchant', x: 0, z: 9.5, facing: Math.PI },
  last: { id: 'brother_halven_marsh', x: -95, z: 505, facing: Math.PI },
};

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const sourceRoot = resolve(projectRoot, '..', '..', 'dev', 'world-of-claudecraft');
const sourceManifestPath = join(projectRoot, 'reference', 'current-head', 'source_manifest.json');
const extractorPath = join(scriptDirectory, 'm3_npc_placement_source_extract.mjs');
const loaderUrl = pathToFileURL(join(scriptDirectory, 'typescript_git_loader.mjs')).href;
const contractPath = join(projectRoot, 'contracts', 'm3_npc_placement.json');
const zrPath = join(projectRoot, 'scripts', 'woc_game', 'src', 'generated', 'm3_npc_placement.zr');
const checkOnly = process.argv.includes('--check');

main();

function main() {
  execFileSync('git', ['-C', sourceRoot, 'cat-file', '-e', `${SOURCE_COMMIT}^{commit}`]);
  const manifest = JSON.parse(readFileSync(sourceManifestPath, 'utf8'));
  assert(manifest.source_commit === SOURCE_COMMIT, 'WOC source manifest commit drifted');
  const extracted = extract();
  assert(extracted.entries.length === EXPECTED.total, 'NPC total drifted');
  assert(extracted.static_entries.length === EXPECTED.static, 'static NPC count drifted');
  assert(JSON.stringify(extracted.dynamic_ids) === JSON.stringify(EXPECTED.dynamicIds),
    'dynamic NPC identity or order drifted');
  assertNpcSentinel(extracted.static_entries[0], EXPECTED.first, 'first static NPC drifted');
  assertNpcSentinel(extracted.static_entries.at(-1), EXPECTED.last, 'last static NPC drifted');
  const sourceIdentity = gitBlobIdentity('src/sim/data.ts');
  const document = {
    schema_version: 1,
    source_commit: SOURCE_COMMIT,
    generated_by: 'examples/woc/tools/m3_npc_placement_codegen.mjs',
    source_identity: sourceIdentity,
    static_npcs: extracted.static_entries,
    dynamic_npc_ids: extracted.dynamic_ids,
  };
  document.catalog_sha256 = sha256(JSON.stringify({
    source_identity: document.source_identity,
    static_npcs: document.static_npcs,
    dynamic_npc_ids: document.dynamic_npc_ids,
  }));
  const contract = `${JSON.stringify(document, null, 2)}\n`;
  const zr = render(document);
  writeOrCheck(contractPath, contract, 'm3_npc_placement.json');
  writeOrCheck(zrPath, zr, 'm3_npc_placement.zr');
  process.stdout.write(`${checkOnly ? 'checked' : 'generated'} ${document.static_npcs.length} static NPC placements ` +
    `(${document.catalog_sha256.slice(0, 15)})\n`);
}

function extract() {
  const child = spawnSync(process.execPath, [
    '--no-warnings', '--experimental-loader', loaderUrl, extractorPath,
  ], {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
    env: { ...process.env, WOC_GIT_ROOT: sourceRoot, WOC_GIT_COMMIT: SOURCE_COMMIT },
  });
  assert(child.status === 0, child.stderr || `NPC extractor exited ${child.status}`);
  return JSON.parse(child.stdout);
}

function render(document) {
  const lines = [
    '// Generated by examples/woc/tools/m3_npc_placement_codegen.mjs.',
    `// Source ${document.source_commit}; static constructor-order NPC placements; do not edit.`,
    '',
    'npcIndexIsValid(index: int): bool {',
    `    return index >= 0 && index < ${document.static_npcs.length};`,
    '}',
    '',
    'pub catalogSha(required: bool): string {',
    '    if (!required) { throw "woc NPC placement catalog is required"; }',
    `    return ${zrString(document.catalog_sha256)};`,
    '}',
    '',
    'pub staticNpcCount(required: bool): int {',
    '    if (!required) { throw "woc static NPC count is required"; }',
    `    return ${document.static_npcs.length};`,
    '}',
    '',
    'pub staticNpcId(index: int, required: bool): string {',
    '    if (!required || !npcIndexIsValid(index)) { throw "woc static NPC id is invalid"; }',
  ];
  document.static_npcs.forEach((entry, index) => lines.push(
    `    if (index == ${index}) { return ${zrString(entry.id)}; }`,
  ));
  lines.push('    throw "woc static NPC id is invalid";', '}', '',
    'pub rawCoordinate(index: int, axis: int, required: bool): float {',
    '    if (!required || !npcIndexIsValid(index) || (axis != 1 && axis != 2)) {',
    '        throw "woc static NPC coordinate is invalid";',
    '    }');
  document.static_npcs.forEach((entry, index) => lines.push(
    `    if (index == ${index}) { return axis == 1 ? ${zrNumber(entry.x)} : ${zrNumber(entry.z)}; }`,
  ));
  lines.push('    throw "woc static NPC coordinate is invalid";', '}', '',
    'pub facing(index: int, required: bool): float {',
    '    if (!required || !npcIndexIsValid(index)) { throw "woc static NPC facing is invalid"; }');
  document.static_npcs.forEach((entry, index) => lines.push(
    `    if (index == ${index}) { return ${zrNumber(entry.facing)}; }`,
  ));
  lines.push('    throw "woc static NPC facing is invalid";', '}', '',
    'pub dynamicNpcCount(required: bool): int {',
    '    if (!required) { throw "woc dynamic NPC count is required"; }',
    `    return ${document.dynamic_npc_ids.length};`,
    '}', '',
    'pub dynamicNpcId(index: int, required: bool): string {',
    `    if (!required || index < 0 || index >= ${document.dynamic_npc_ids.length}) {`,
    '        throw "woc dynamic NPC id is invalid";',
    '    }');
  document.dynamic_npc_ids.forEach((id, index) => lines.push(
    `    if (index == ${index}) { return ${zrString(id)}; }`,
  ));
  lines.push('    throw "woc dynamic NPC id is invalid";', '}', '', 'pub contractTest(): int {',
    `    if (staticNpcCount(true) != ${document.static_npcs.length} || dynamicNpcCount(true) != ${document.dynamic_npc_ids.length} ||`,
    `        staticNpcId(0, true) != ${zrString(document.static_npcs[0].id)} ||`,
    `        staticNpcId(${document.static_npcs.length - 1}, true) != ${zrString(document.static_npcs.at(-1).id)} ||`,
    `        dynamicNpcId(0, true) != ${zrString(document.dynamic_npc_ids[0])} ||`,
    `        dynamicNpcId(${document.dynamic_npc_ids.length - 1}, true) != ${zrString(document.dynamic_npc_ids.at(-1))}) {`,
    '        return -1;',
    '    }',
    '    return 1;',
    '}',
  );
  return `${lines.join('\n')}\n`;
}

function gitBlobIdentity(sourcePath) {
  const sourceText = execFileSync('git', ['-C', sourceRoot, 'show', `${SOURCE_COMMIT}:${sourcePath}`], {
    encoding: 'utf8',
  });
  const blob = execFileSync('git', ['-C', sourceRoot, 'rev-parse', `${SOURCE_COMMIT}:${sourcePath}`], {
    encoding: 'utf8',
  }).trim();
  return { source_path: sourcePath, git_blob: blob, sha256: sha256Text(sourceText) };
}

function writeOrCheck(path, content, name) {
  if (checkOnly) {
    assert(existsSync(path), `${name} is missing; run the NPC placement generator`);
    assert(readFileSync(path, 'utf8') === content, `${name} is stale; run the NPC placement generator`);
    return;
  }
  writeFileSync(path, content, 'utf8');
}

function zrString(value) { return JSON.stringify(value); }
function zrNumber(value) {
  assert(Number.isFinite(value), 'NPC placement contains a non-finite number');
  return String(value);
}
function sha256(value) { return sha256Text(value); }
function sha256Text(value) { return createHash('sha256').update(value).digest('hex'); }
function assertNpcSentinel(actual, expected, message) {
  assert(actual.id === expected.id && actual.dynamic === false && actual.x === expected.x &&
    actual.z === expected.z && actual.facing === expected.facing, message);
}
function assert(condition, message) { if (!condition) throw new Error(message); }

// 调用端：npm run generate (tools/package.json)；职责：为 golden 轨迹字符串分配确定性的线协议 ID，供 JSON、Zr 和 Rust 对齐使用。
// 当前版本的 54 条 golden 轨迹决定从 1 开始的字典 ID 和共享线格式指纹。

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const SOURCE_COMMIT = '5ef9f7cb21cd8875b6d2c49701015dfcd78de35a';
const goldenRoot = join(projectRoot, 'reference', 'current-head', 'parity', 'golden');
const jsonOutput = join(projectRoot, 'reference', 'current-head', 'trace_symbols.json');
const zrOutput = join(projectRoot, 'scripts', 'woc_game', 'src', 'generated', 'trace_symbols.zr');
const rustOutput = join(
  projectRoot,
  'native',
  'crates',
  'woc_parity',
  'src',
  'generated_trace_symbols.rs',
);
const checkOnly = process.argv.includes('--check');
const HASH_RESULT = /^[0-9a-f]{8}$/u;
const NON_FINITE_SENTINELS = new Set(['Infinity', '-Infinity', 'NaN']);

main();

// 对 golden 的唯一字符串排序后，分配从 1 开始的 ID 和共享的低 60 位线格式指纹。
function main() {
  const files = readdirSync(goldenRoot).filter((name) => name.endsWith('.json')).sort();
  invariant(files.length === 54, `expected 54 current-head golden traces, found ${files.length}`);

  const symbols = new Map();
  for (const file of files) {
    const document = JSON.parse(readFileSync(join(goldenRoot, file), 'utf8'));
    collect(document, symbols);
  }

  const baseEntries = [...symbols]
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([text, kinds], index) => ({
      id: index + 1,
      name: symbolName(text, kinds, index),
      text,
      kinds: [...kinds].sort(),
    }));
  const entries = baseEntries;
  const fingerprintSource = entries.map((entry) => `${entry.id}\0${entry.text}\n`).join('');
  const sha256 = createHash('sha256').update(fingerprintSource, 'utf8').digest('hex');
  // Keep the VM-side numeric literal below 2^60 while retaining a strong drift guard.
  const fingerprintHex = sha256.slice(0, 15);
  const fingerprint = BigInt(`0x${fingerprintHex}`);
  const document = {
    schema_version: 1,
    source_commit: SOURCE_COMMIT,
    golden_files: files.length,
    golden_symbol_count: baseEntries.length,
    hidden_symbol_count: 0,
    symbol_count: entries.length,
    sha256,
    wire_fingerprint_hex: fingerprintHex,
    entries,
  };

  const outputs = new Map([
    [jsonOutput, `${JSON.stringify(document, null, 2)}\n`],
    [zrOutput, renderZr(entries, fingerprint)],
    [rustOutput, renderRust(entries, fingerprint, fingerprintHex)],
  ]);
  for (const [path, content] of outputs) writeOrCheck(path, content);
  process.stdout.write(
    `${checkOnly ? 'checked' : 'generated'} ${entries.length} WOC trace symbols (${fingerprintHex})\n`,
  );
}

// 字典只收对象键和非哨兵字符串；摘要字符串仍保留原始字段值。
function collect(value, symbols) {
  if (Array.isArray(value)) {
    for (const item of value) collect(item, symbols);
    return;
  }
  if (value && typeof value === 'object') {
    for (const [key, item] of Object.entries(value)) {
      addSymbol(symbols, key, 'key');
      collect(item, symbols);
    }
    return;
  }
  if (typeof value === 'string' && !HASH_RESULT.test(value) && !NON_FINITE_SENTINELS.has(value)) {
    addSymbol(symbols, value, 'value');
  }
}

function addSymbol(symbols, text, kind) {
  const kinds = symbols.get(text) ?? new Set();
  kinds.add(kind);
  symbols.set(text, kinds);
}

// 稳定的哈希后缀避免规范化后外观相同的名称发生标识符冲突。
function symbolName(text, kinds, ordinal) {
  const hash = createHash('sha256').update(text, 'utf8').digest('hex').slice(0, 8);
  if (text.length > 64 || /[^A-Za-z0-9_]/u.test(text)) return `Text_${hash}`;
  const words = text.split(/_+/u).filter(Boolean);
  let body = words.map((word) => word[0].toUpperCase() + word.slice(1)).join('');
  if (!body) body = `Empty${ordinal}`;
  if (/^[0-9]/u.test(body)) body = `N${body}`;
  const prefix = kinds.has('key') ? 'Key' : 'Value';
  return `${prefix}${body}_${hash}`;
}

function renderZr(entries, fingerprint) {
  return `// Generated by examples/woc/tools/trace_symbol_codegen.mjs. Do not edit.\n` +
    `// Full id-to-text mapping: examples/woc/reference/current-head/trace_symbols.json.\n` +
    `pub symbol(id: int): int {\n` +
    `    if (id <= 0 || id > ${entries.length}) {\n` +
    `        throw "WOC trace symbol id is out of range";\n` +
    `    }\n` +
    `    return id;\n` +
    `}\n\n` +
    `pub fingerprint(): uint {\n    return <uint>${fingerprint};\n}\n`;
}

function renderRust(entries, fingerprint, fingerprintHex) {
  const rows = ['    "",', ...entries.map((entry) => `    ${JSON.stringify(entry.text)},`)];
  return `// Generated by examples/woc/tools/trace_symbol_codegen.mjs. Do not edit.\n` +
    `pub const TRACE_SYMBOL_FINGERPRINT: u64 = 0x${fingerprintHex};\n` +
    `pub const TRACE_SYMBOLS: &[&str] = &[\n${rows.join('\n')}\n];\n\n` +
    `pub fn resolve_trace_symbol(id: u16) -> Option<&'static str> {\n` +
    `    if id == 0 {\n` +
    `        None\n` +
    `    } else {\n` +
    `        TRACE_SYMBOLS.get(usize::from(id)).copied()\n` +
    `    }\n` +
    `}\n` +
    `\npub fn trace_symbol_id(value: &str) -> Option<u16> {\n` +
    `    TRACE_SYMBOLS\n` +
    `        .iter()\n` +
    `        .enumerate()\n` +
    `        .skip(1)\n` +
    `        .find_map(|(index, candidate)| {\n` +
    `            (*candidate == value)\n` +
    `                .then(|| u16::try_from(index).ok())\n` +
    `                .flatten()\n` +
    `        })\n` +
    `}\n`;
}

function writeOrCheck(path, content) {
  if (checkOnly) {
    invariant(existsSync(path), `${path} is missing; run npm run generate`);
    invariant(readFileSync(path, 'utf8') === content, `${path} is stale; run npm run generate`);
    return;
  }
  writeFileSync(path, content, 'utf8');
}

function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

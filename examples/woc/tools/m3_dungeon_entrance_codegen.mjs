import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SOURCE_COMMIT = '5ef9f7cb21cd8875b6d2c49701015dfcd78de35a';
const EXPECTED = {
  instanceSlots: 24,
  dungeons: [
    { id: 'hollow_crypt', index: 0, overworld_door: true, x: 80, z: 90 },
    { id: 'sunken_bastion', index: 1, overworld_door: true, x: 45, z: 515 },
    { id: 'gravewyrm_sanctum', index: 2, overworld_door: true, x: 0, z: 858 },
    { id: 'drowned_temple', index: 3, overworld_door: true, x: -70, z: 792 },
    { id: 'nythraxis_crypt', index: 4, overworld_door: true, x: -152, z: 610 },
    { id: 'nythraxis_boss_arena', index: 5, overworld_door: false, x: -152, z: 610 },
  ],
};

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const sourceRoot = resolve(projectRoot, '..', '..', 'dev', 'world-of-claudecraft');
const sourceManifestPath = join(projectRoot, 'reference', 'current-head', 'source_manifest.json');
const extractorPath = join(scriptDirectory, 'm3_dungeon_entrance_source_extract.mjs');
const loaderUrl = pathToFileURL(join(scriptDirectory, 'typescript_git_loader.mjs')).href;
const contractPath = join(projectRoot, 'contracts', 'm3_dungeon_entrance.json');
const zrPath = join(projectRoot, 'scripts', 'woc_game', 'src', 'generated', 'm3_dungeon_entrance.zr');
const checkOnly = process.argv.includes('--check');

main();

function main() {
  execFileSync('git', ['-C', sourceRoot, 'cat-file', '-e', `${SOURCE_COMMIT}^{commit}`]);
  const manifest = JSON.parse(readFileSync(sourceManifestPath, 'utf8'));
  assert(manifest.source_commit === SOURCE_COMMIT, 'WOC source manifest commit drifted');
  const extracted = extract();
  assert(extracted.instance_slot_count === EXPECTED.instanceSlots, 'instance slot count drifted');
  assert(extracted.dungeons.length === EXPECTED.dungeons.length, 'dungeon list count drifted');
  for (let index = 0; index < EXPECTED.dungeons.length; index++) {
    assertSentinel(extracted.dungeons[index], EXPECTED.dungeons[index], `dungeon ${index} drifted`);
  }
  const document = {
    schema_version: 1,
    source_commit: SOURCE_COMMIT,
    generated_by: 'examples/woc/tools/m3_dungeon_entrance_codegen.mjs',
    source_identity: gitBlobIdentity('src/sim/data.ts'),
    instance_slot_count: extracted.instance_slot_count,
    dungeons: extracted.dungeons,
  };
  document.catalog_sha256 = sha256(JSON.stringify({
    source_identity: document.source_identity,
    instance_slot_count: document.instance_slot_count,
    dungeons: document.dungeons,
  }));
  const contract = `${JSON.stringify(document, null, 2)}\n`;
  const zr = render(document);
  writeOrCheck(contractPath, contract, 'm3_dungeon_entrance.json');
  writeOrCheck(zrPath, zr, 'm3_dungeon_entrance.zr');
  process.stdout.write(`${checkOnly ? 'checked' : 'generated'} ${document.dungeons.length} dungeon entries ` +
    `(${document.catalog_sha256.slice(0, 15)})\n`);
}

function extract() {
  const child = spawnSync(process.execPath, [
    '--no-warnings', '--experimental-loader', loaderUrl, extractorPath,
  ], {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
    env: { ...process.env, WOC_GIT_ROOT: sourceRoot, WOC_GIT_COMMIT: SOURCE_COMMIT },
  });
  assert(child.status === 0, child.stderr || `dungeon entrance extractor exited ${child.status}`);
  return JSON.parse(child.stdout);
}

function render(document) {
  const entries = document.dungeons;
  const lines = [
    '// Generated by examples/woc/tools/m3_dungeon_entrance_codegen.mjs.',
    `// Source ${document.source_commit}; DUNGEON_LIST index order; do not edit.`,
    '',
    'dungeonIndexIsValid(index: int): bool {',
    `    return index >= 0 && index < ${entries.length};`,
    '}',
    '',
    'pub catalogSha(required: bool): string {',
    '    if (!required) { throw "woc dungeon entrance catalog is required"; }',
    `    return ${zrString(document.catalog_sha256)};`,
    '}',
    '',
    'pub dungeonCount(required: bool): int {',
    '    if (!required) { throw "woc dungeon entrance count is required"; }',
    `    return ${entries.length};`,
    '}',
    '',
    'pub instanceSlotCount(required: bool): int {',
    '    if (!required) { throw "woc instance slot count is required"; }',
    `    return ${document.instance_slot_count};`,
    '}',
    '',
  ];
  appendString(lines, entries, 'dungeonId', 'id');
  appendString(lines, entries, 'dungeonName', 'name');
  appendNumber(lines, entries, 'dungeonIndex', 'index', 'int');
  appendBool(lines, entries, 'hasOverworldDoor', 'overworld_door');
  lines.push('pub doorCoordinate(index: int, axis: int, required: bool): float {',
    '    if (!required || !dungeonIndexIsValid(index) || (axis != 1 && axis != 2)) {',
    '        throw "woc dungeon door coordinate is invalid";',
    '    }');
  entries.forEach((entry, index) => lines.push(
    `    if (index == ${index}) { return axis == 1 ? ${zrNumber(entry.x)} : ${zrNumber(entry.z)}; }`,
  ));
  lines.push('    throw "woc dungeon door coordinate is invalid";', '}', '', 'pub contractTest(): int {',
    `    if (dungeonCount(true) != ${entries.length} || instanceSlotCount(true) != ${document.instance_slot_count} ||`,
    '        dungeonId(0, true) != "hollow_crypt" || dungeonId(5, true) != "nythraxis_boss_arena" ||',
    '        !hasOverworldDoor(4, true) || hasOverworldDoor(5, true) ||',
    '        doorCoordinate(3, 1, true) != -70.0 || doorCoordinate(4, 2, true) != 610.0) {',
    '        return -1;',
    '    }',
    '    return 1;',
    '}',
  );
  return `${lines.join('\n')}\n`;
}

function appendString(lines, entries, functionName, field) {
  lines.push(`pub ${functionName}(index: int, required: bool): string {`,
    '    if (!required || !dungeonIndexIsValid(index)) { throw "woc dungeon index is invalid"; }');
  entries.forEach((entry, index) => lines.push(`    if (index == ${index}) { return ${zrString(entry[field])}; }`));
  lines.push('    throw "woc dungeon index is invalid";', '}', '');
}

function appendNumber(lines, entries, functionName, field, type) {
  lines.push(`pub ${functionName}(index: int, required: bool): ${type} {`,
    '    if (!required || !dungeonIndexIsValid(index)) { throw "woc dungeon index is invalid"; }');
  entries.forEach((entry, index) => lines.push(`    if (index == ${index}) { return ${entry[field]}; }`));
  lines.push('    throw "woc dungeon index is invalid";', '}', '');
}

function appendBool(lines, entries, functionName, field) {
  lines.push(`pub ${functionName}(index: int, required: bool): bool {`,
    '    if (!required || !dungeonIndexIsValid(index)) { throw "woc dungeon index is invalid"; }');
  entries.forEach((entry, index) => lines.push(`    if (index == ${index}) { return ${entry[field] ? 'true' : 'false'}; }`));
  lines.push('    throw "woc dungeon index is invalid";', '}', '');
}

function assertSentinel(actual, expected, message) {
  assert(actual.id === expected.id && actual.index === expected.index &&
    actual.overworld_door === expected.overworld_door && actual.x === expected.x && actual.z === expected.z, message);
}

function gitBlobIdentity(sourcePath) {
  const sourceText = execFileSync('git', ['-C', sourceRoot, 'show', `${SOURCE_COMMIT}:${sourcePath}`], {
    encoding: 'utf8',
  });
  const blob = execFileSync('git', ['-C', sourceRoot, 'rev-parse', `${SOURCE_COMMIT}:${sourcePath}`], {
    encoding: 'utf8',
  }).trim();
  return { source_path: sourcePath, git_blob: blob, sha256: sha256Text(sourceText) };
}

function writeOrCheck(path, content, name) {
  if (checkOnly) {
    assert(existsSync(path), `${name} is missing; run the dungeon entrance generator`);
    assert(readFileSync(path, 'utf8') === content, `${name} is stale; run the dungeon entrance generator`);
    return;
  }
  writeFileSync(path, content, 'utf8');
}

function zrString(value) { return JSON.stringify(value); }
function zrNumber(value) {
  assert(Number.isFinite(value), 'dungeon entrance contains a non-finite number');
  return String(value);
}
function sha256(value) { return sha256Text(value); }
function sha256Text(value) { return createHash('sha256').update(value).digest('hex'); }
function assert(condition, message) { if (!condition) throw new Error(message); }

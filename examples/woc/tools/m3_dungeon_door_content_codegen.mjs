import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SOURCE_COMMIT = '5ef9f7cb21cd8875b6d2c49701015dfcd78de35a';
const EXPECTED_CLEAR_RADIUS = 20;
const EXPECTED_DOORS = [
  { x: 80, z: 90 },
  { x: 45, z: 515 },
  { x: 0, z: 858 },
  { x: -152, z: 610 },
  { x: -70, z: 792 },
];
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const sourceRoot = resolve(projectRoot, '..', '..', 'dev', 'world-of-claudecraft');
const sourceManifestPath = join(projectRoot, 'reference', 'current-head', 'source_manifest.json');
const extractorPath = join(scriptDirectory, 'm3_dungeon_door_content_source_extract.mjs');
const loaderUrl = pathToFileURL(join(scriptDirectory, 'typescript_git_loader.mjs')).href;
const contractPath = join(projectRoot, 'contracts', 'm3_dungeon_door_content.json');
const zrPath = join(projectRoot, 'scripts', 'woc_game', 'src', 'world', 'dungeon_door_content.zr');
const checkOnly = process.argv.includes('--check');

main();

function main() {
  execFileSync('git', ['-C', sourceRoot, 'cat-file', '-e', `${SOURCE_COMMIT}^{commit}`]);
  const manifest = JSON.parse(readFileSync(sourceManifestPath, 'utf8'));
  assert(manifest.source_commit === SOURCE_COMMIT, 'WOC source manifest commit drifted');

  const extracted = extractContent();
  assert(extracted.clear_radius === EXPECTED_CLEAR_RADIUS, 'dungeon door clear radius drifted');
  assert(
    JSON.stringify(extracted.doors) === JSON.stringify(EXPECTED_DOORS),
    'dungeon door identity or source order drifted',
  );
  assert(
    extracted.doors.every((door) => Number.isFinite(door.x) && Number.isFinite(door.z)),
    'dungeon door coordinate is invalid',
  );

  const dataText = gitShow('src/sim/data.ts');
  const locomotionText = gitShow('src/sim/mob/locomotion.ts');
  const clearanceText = gitShow('src/sim/dungeon_door_clearance.ts');
  assert(
    clearanceText.includes('export const DOOR_CLEAR_RADIUS = MAX_AGGRO_RADIUS;') &&
      clearanceText.includes('for (const d of Object.values(DUNGEONS))') &&
      clearanceText.includes('if (dist >= DOOR_CLEAR_RADIUS) continue;') &&
      clearanceText.includes('if (dist < 1e-6)'),
    'dungeon door clearance source structure drifted',
  );

  const catalog = {
    schema_version: 1,
    source_commit: SOURCE_COMMIT,
    generated_by: 'examples/woc/tools/m3_dungeon_door_content_codegen.mjs',
    source_sha256: {
      'src/sim/data.ts': sha256(dataText),
      'src/sim/mob/locomotion.ts': sha256(locomotionText),
      'src/sim/dungeon_door_clearance.ts': sha256(clearanceText),
    },
    clear_radius: extracted.clear_radius,
    doors: extracted.doors,
  };
  catalog.content_sha256 = sha256(JSON.stringify({
    clear_radius: catalog.clear_radius,
    doors: catalog.doors,
  }));

  verifyOrWrite(contractPath, `${JSON.stringify(catalog, null, 2)}\n`);
  verifyOrWrite(zrPath, renderZr(catalog));
}

function extractContent() {
  const child = spawnSync(process.execPath, [
    '--no-warnings',
    '--experimental-loader',
    loaderUrl,
    extractorPath,
  ], {
    encoding: 'utf8',
    maxBuffer: 16 * 1024 * 1024,
    env: { ...process.env, WOC_GIT_ROOT: sourceRoot, WOC_GIT_COMMIT: SOURCE_COMMIT },
  });
  assert(child.status === 0, child.stderr || `dungeon door source extractor exited ${child.status}`);
  return JSON.parse(child.stdout);
}

function gitShow(sourcePath) {
  return execFileSync(
    'git',
    ['-C', sourceRoot, 'show', `${SOURCE_COMMIT}:${sourcePath}`],
    { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 },
  );
}

function renderZr(catalog) {
  const { clear_radius: clearRadius, doors } = catalog;
  const lines = [
    '// Generated by tools/m3_dungeon_door_content_codegen.mjs from pinned WOC source.',
    '// This table owns only source-order door coordinates and their clear radius.',
    '',
    'doorIndexIsValid(index: int): bool {',
    `    return index >= 0 && index < ${doors.length};`,
    '}',
    '',
    'pub dungeonDoorClearRadius(required: bool): float {',
    '    if (!required) {',
    '        throw "woc dungeon door clear radius is required";',
    '    }',
    `    return ${formatNumber(clearRadius)};`,
    '}',
    '',
    'pub dungeonDoorCount(required: bool): int {',
    '    if (!required) {',
    '        throw "woc dungeon door count is required";',
    '    }',
    `    return ${doors.length};`,
    '}',
    '',
    renderIndexedFloat('dungeonDoorX', 'dungeon door x', doors.map((door) => door.x)),
    '',
    renderIndexedFloat('dungeonDoorZ', 'dungeon door z', doors.map((door) => door.z)),
    '',
    'pub contractTest(): int {',
    `    if (dungeonDoorClearRadius(true) != ${formatNumber(clearRadius)} || dungeonDoorCount(true) != ${doors.length} ||`,
  ];
  for (let index = 0; index < doors.length; index++) {
    const door = doors[index];
    const suffix = index + 1 < doors.length ? ' ||' : ') {';
    lines.push(
      `        dungeonDoorX(${index}, true) != ${formatNumber(door.x)} || dungeonDoorZ(${index}, true) != ${formatNumber(door.z)}${suffix}`,
    );
  }
  lines.push('        return -1;', '    }', '    return 1;', '}', '');
  return lines.join('\n');
}

function renderIndexedFloat(name, label, values) {
  const lines = [
    `pub ${name}(index: int, required: bool): float {`,
    '    if (!required || !doorIndexIsValid(index)) {',
    `        throw "woc ${label} is invalid";`,
    '    }',
  ];
  for (let index = 0; index + 1 < values.length; index++) {
    lines.push(`    if (index == ${index}) {`, `        return ${formatNumber(values[index])};`, '    }');
  }
  lines.push(`    return ${formatNumber(values.at(-1))};`, '}');
  return lines.join('\n');
}

function verifyOrWrite(path, text) {
  if (checkOnly) {
    assert(existsSync(path), `generated output is missing: ${path}`);
    assert(readFileSync(path, 'utf8') === text, `generated output drifted: ${path}`);
    return;
  }
  writeFileSync(path, text);
}

function formatNumber(value) {
  assert(Number.isFinite(value), `cannot emit non-finite number ${value}`);
  return Number.isInteger(value) ? `${value}.0` : value.toString();
}

function sha256(text) {
  return createHash('sha256').update(text).digest('hex');
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SOURCE_COMMIT = '5ef9f7cb21cd8875b6d2c49701015dfcd78de35a';
const EXPECTED = {
  definitions: 18,
  entries: 55,
  first: { item_id: 'supply_crate', name: 'Stolen Supply Crate', x: 58, z: -58 },
  last: { item_id: 'moongate_rubbing', name: 'Warded Shore-Rock', x: -64, z: 794 },
};

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const sourceRoot = resolve(projectRoot, '..', '..', 'dev', 'world-of-claudecraft');
const sourceManifestPath = join(projectRoot, 'reference', 'current-head', 'source_manifest.json');
const extractorPath = join(scriptDirectory, 'm3_ground_object_placement_source_extract.mjs');
const loaderUrl = pathToFileURL(join(scriptDirectory, 'typescript_git_loader.mjs')).href;
const contractPath = join(projectRoot, 'contracts', 'm3_ground_object_placement.json');
const zrPath = join(projectRoot, 'scripts', 'woc_game', 'src', 'generated', 'm3_ground_object_placement.zr');
const checkOnly = process.argv.includes('--check');

main();

function main() {
  execFileSync('git', ['-C', sourceRoot, 'cat-file', '-e', `${SOURCE_COMMIT}^{commit}`]);
  const manifest = JSON.parse(readFileSync(sourceManifestPath, 'utf8'));
  assert(manifest.source_commit === SOURCE_COMMIT, 'WOC source manifest commit drifted');
  const extracted = extract();
  assert(extracted.definition_count === EXPECTED.definitions, 'ground-object definition count drifted');
  assert(extracted.entries.length === EXPECTED.entries, 'ground-object placement count drifted');
  assertEntry(extracted.entries[0], EXPECTED.first, 'first ground-object placement drifted');
  assertEntry(extracted.entries.at(-1), EXPECTED.last, 'last ground-object placement drifted');
  const document = {
    schema_version: 1,
    source_commit: SOURCE_COMMIT,
    generated_by: 'examples/woc/tools/m3_ground_object_placement_codegen.mjs',
    source_identity: gitBlobIdentity('src/sim/data.ts'),
    definition_count: extracted.definition_count,
    placements: extracted.entries,
  };
  document.catalog_sha256 = sha256(JSON.stringify({
    source_identity: document.source_identity,
    definition_count: document.definition_count,
    placements: document.placements,
  }));
  const contract = `${JSON.stringify(document, null, 2)}\n`;
  const zr = render(document);
  writeOrCheck(contractPath, contract, 'm3_ground_object_placement.json');
  writeOrCheck(zrPath, zr, 'm3_ground_object_placement.zr');
  process.stdout.write(`${checkOnly ? 'checked' : 'generated'} ${document.placements.length} ground-object placements ` +
    `(${document.catalog_sha256.slice(0, 15)})\n`);
}

function extract() {
  const child = spawnSync(process.execPath, [
    '--no-warnings', '--experimental-loader', loaderUrl, extractorPath,
  ], {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
    env: { ...process.env, WOC_GIT_ROOT: sourceRoot, WOC_GIT_COMMIT: SOURCE_COMMIT },
  });
  assert(child.status === 0, child.stderr || `ground-object extractor exited ${child.status}`);
  return JSON.parse(child.stdout);
}

function render(document) {
  const entries = document.placements;
  const lines = [
    '// Generated by examples/woc/tools/m3_ground_object_placement_codegen.mjs.',
    `// Source ${document.source_commit}; flattened constructor-order placements; do not edit.`,
    '',
    'objectIndexIsValid(index: int): bool {',
    `    return index >= 0 && index < ${entries.length};`,
    '}',
    '',
    'pub catalogSha(required: bool): string {',
    '    if (!required) { throw "woc ground-object placement catalog is required"; }',
    `    return ${zrString(document.catalog_sha256)};`,
    '}',
    '',
    'pub placementCount(required: bool): int {',
    '    if (!required) { throw "woc ground-object placement count is required"; }',
    `    return ${entries.length};`,
    '}',
    '',
    'pub itemId(index: int, required: bool): string {',
    '    if (!required || !objectIndexIsValid(index)) { throw "woc ground-object item index is invalid"; }',
  ];
  appendCases(lines, entries, (entry) => zrString(entry.item_id));
  lines.push('    throw "woc ground-object item index is invalid";', '}', '',
    'pub name(index: int, required: bool): string {',
    '    if (!required || !objectIndexIsValid(index)) { throw "woc ground-object name index is invalid"; }');
  appendCases(lines, entries, (entry) => zrString(entry.name));
  lines.push('    throw "woc ground-object name index is invalid";', '}', '',
    'pub rawCoordinate(index: int, axis: int, required: bool): float {',
    '    if (!required || !objectIndexIsValid(index) || (axis != 1 && axis != 2)) {',
    '        throw "woc ground-object coordinate is invalid";',
    '    }');
  appendCases(lines, entries, (entry) => `axis == 1 ? ${zrNumber(entry.x)} : ${zrNumber(entry.z)}`);
  lines.push('    throw "woc ground-object coordinate is invalid";', '}', '', 'pub contractTest(): int {',
    `    if (placementCount(true) != ${entries.length} || itemId(0, true) != ${zrString(entries[0].item_id)} ||`,
    `        itemId(${entries.length - 1}, true) != ${zrString(entries.at(-1).item_id)} ||`,
    `        name(0, true) != ${zrString(entries[0].name)} ||`,
    `        rawCoordinate(${entries.length - 1}, 1, true) != ${zrNumber(entries.at(-1).x)} ||`,
    `        rawCoordinate(${entries.length - 1}, 2, true) != ${zrNumber(entries.at(-1).z)}) {`,
    '        return -1;',
    '    }',
    '    return 1;',
    '}',
  );
  return `${lines.join('\n')}\n`;
}

function appendCases(lines, entries, value) {
  entries.forEach((entry, index) => lines.push(`    if (index == ${index}) { return ${value(entry)}; }`));
}

function assertEntry(actual, expected, message) {
  assert(actual.item_id === expected.item_id && actual.name === expected.name &&
    actual.x === expected.x && actual.z === expected.z, message);
}

function gitBlobIdentity(sourcePath) {
  const sourceText = execFileSync('git', ['-C', sourceRoot, 'show', `${SOURCE_COMMIT}:${sourcePath}`], {
    encoding: 'utf8',
  });
  const blob = execFileSync('git', ['-C', sourceRoot, 'rev-parse', `${SOURCE_COMMIT}:${sourcePath}`], {
    encoding: 'utf8',
  }).trim();
  return { source_path: sourcePath, git_blob: blob, sha256: sha256Text(sourceText) };
}

function writeOrCheck(path, content, name) {
  if (checkOnly) {
    assert(existsSync(path), `${name} is missing; run the ground-object placement generator`);
    assert(readFileSync(path, 'utf8') === content, `${name} is stale; run the ground-object placement generator`);
    return;
  }
  writeFileSync(path, content, 'utf8');
}

function zrString(value) { return JSON.stringify(value); }
function zrNumber(value) {
  assert(Number.isFinite(value), 'ground-object placement contains a non-finite number');
  return String(value);
}
function sha256(value) { return sha256Text(value); }
function sha256Text(value) { return createHash('sha256').update(value).digest('hex'); }
function assert(condition, message) { if (!condition) throw new Error(message); }

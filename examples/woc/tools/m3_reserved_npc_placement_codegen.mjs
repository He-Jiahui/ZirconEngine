import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SOURCE_COMMIT = '5ef9f7cb21cd8875b6d2c49701015dfcd78de35a';
const EXPECTED = [
  { role: 'groundskeeper_bram', npc_id: 'groundskeeper_bram', entity_id: 1000000000, x: -6, z: -82 },
  { role: 'fury', npc_id: 'fury', entity_id: 1000000001, x: -11, z: 1 },
];

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const sourceRoot = resolve(projectRoot, '..', '..', 'dev', 'world-of-claudecraft');
const sourceManifestPath = join(projectRoot, 'reference', 'current-head', 'source_manifest.json');
const extractorPath = join(scriptDirectory, 'm3_reserved_npc_placement_source_extract.mjs');
const loaderUrl = pathToFileURL(join(scriptDirectory, 'typescript_git_loader.mjs')).href;
const contractPath = join(projectRoot, 'contracts', 'm3_reserved_npc_placement.json');
const zrPath = join(projectRoot, 'scripts', 'woc_game', 'src', 'generated', 'm3_reserved_npc_placement.zr');
const checkOnly = process.argv.includes('--check');

main();

function main() {
  execFileSync('git', ['-C', sourceRoot, 'cat-file', '-e', `${SOURCE_COMMIT}^{commit}`]);
  const manifest = JSON.parse(readFileSync(sourceManifestPath, 'utf8'));
  assert(manifest.source_commit === SOURCE_COMMIT, 'WOC source manifest commit drifted');
  const extracted = extract();
  assert(extracted.entries.length === EXPECTED.length, 'reserved NPC count drifted');
  for (let index = 0; index < EXPECTED.length; index++) {
    assertEntry(extracted.entries[index], EXPECTED[index], `reserved NPC ${index} drifted`);
  }
  const document = {
    schema_version: 1,
    source_commit: SOURCE_COMMIT,
    generated_by: 'examples/woc/tools/m3_reserved_npc_placement_codegen.mjs',
    source_identity: {
      'src/sim/data.ts': gitBlobIdentity('src/sim/data.ts'),
      'src/sim/social/vale_cup.ts': gitBlobIdentity('src/sim/social/vale_cup.ts'),
      'src/sim/content/pvp_honor.ts': gitBlobIdentity('src/sim/content/pvp_honor.ts'),
    },
    reserved_npcs: extracted.entries,
  };
  document.catalog_sha256 = sha256(JSON.stringify({
    source_identity: document.source_identity,
    reserved_npcs: document.reserved_npcs,
  }));
  const contract = `${JSON.stringify(document, null, 2)}\n`;
  const zr = render(document);
  writeOrCheck(contractPath, contract, 'm3_reserved_npc_placement.json');
  writeOrCheck(zrPath, zr, 'm3_reserved_npc_placement.zr');
  process.stdout.write(`${checkOnly ? 'checked' : 'generated'} ${document.reserved_npcs.length} reserved NPC placements ` +
    `(${document.catalog_sha256.slice(0, 15)})\n`);
}

function extract() {
  const child = spawnSync(process.execPath, [
    '--no-warnings', '--experimental-loader', loaderUrl, extractorPath,
  ], {
    encoding: 'utf8',
    maxBuffer: 32 * 1024 * 1024,
    env: { ...process.env, WOC_GIT_ROOT: sourceRoot, WOC_GIT_COMMIT: SOURCE_COMMIT },
  });
  assert(child.status === 0, child.stderr || `reserved NPC extractor exited ${child.status}`);
  return JSON.parse(child.stdout);
}

function render(document) {
  const entries = document.reserved_npcs;
  const lines = [
    '// Generated by examples/woc/tools/m3_reserved_npc_placement_codegen.mjs.',
    `// Source ${document.source_commit}; post-roster reserved NPC placements; do not edit.`,
    '',
    'reservedNpcIndexIsValid(index: int): bool {',
    `    return index >= 0 && index < ${entries.length};`,
    '}',
    '',
    'pub catalogSha(required: bool): string {',
    '    if (!required) { throw "woc reserved NPC placement catalog is required"; }',
    `    return ${zrString(document.catalog_sha256)};`,
    '}',
    '',
    'pub reservedNpcCount(required: bool): int {',
    '    if (!required) { throw "woc reserved NPC count is required"; }',
    `    return ${entries.length};`,
    '}',
    '',
  ];
  appendString(lines, entries, 'role', 'role');
  appendString(lines, entries, 'npcId', 'npc_id');
  appendString(lines, entries, 'npcName', 'name');
  appendInt(lines, entries, 'entityId', 'entity_id');
  lines.push('pub rawCoordinate(index: int, axis: int, required: bool): float {',
    '    if (!required || !reservedNpcIndexIsValid(index) || (axis != 1 && axis != 2)) {',
    '        throw "woc reserved NPC coordinate is invalid";',
    '    }');
  entries.forEach((entry, index) => lines.push(
    `    if (index == ${index}) { return axis == 1 ? ${zrNumber(entry.x)} : ${zrNumber(entry.z)}; }`,
  ));
  lines.push('    throw "woc reserved NPC coordinate is invalid";', '}', '',
    'pub facing(index: int, required: bool): float {',
    '    if (!required || !reservedNpcIndexIsValid(index)) { throw "woc reserved NPC facing is invalid"; }');
  entries.forEach((entry, index) => lines.push(`    if (index == ${index}) { return ${zrNumber(entry.facing)}; }`));
  lines.push('    throw "woc reserved NPC facing is invalid";', '}', '', 'pub contractTest(): int {',
    `    if (reservedNpcCount(true) != ${entries.length} || role(0, true) != "groundskeeper_bram" ||`,
    '        entityId(0, true) != 1000000000 || npcId(1, true) != "fury" ||',
    '        entityId(1, true) != 1000000001 || rawCoordinate(1, 2, true) != 1.0) {',
    '        return -1;',
    '    }',
    '    return 1;',
    '}',
  );
  return `${lines.join('\n')}\n`;
}

function appendString(lines, entries, functionName, field) {
  lines.push(`pub ${functionName}(index: int, required: bool): string {`,
    '    if (!required || !reservedNpcIndexIsValid(index)) { throw "woc reserved NPC index is invalid"; }');
  entries.forEach((entry, index) => lines.push(`    if (index == ${index}) { return ${zrString(entry[field])}; }`));
  lines.push('    throw "woc reserved NPC index is invalid";', '}', '');
}

function appendInt(lines, entries, functionName, field) {
  lines.push(`pub ${functionName}(index: int, required: bool): int {`,
    '    if (!required || !reservedNpcIndexIsValid(index)) { throw "woc reserved NPC index is invalid"; }');
  entries.forEach((entry, index) => lines.push(`    if (index == ${index}) { return ${entry[field]}; }`));
  lines.push('    throw "woc reserved NPC index is invalid";', '}', '');
}

function assertEntry(actual, expected, message) {
  assert(actual.role === expected.role && actual.npc_id === expected.npc_id &&
    actual.entity_id === expected.entity_id && actual.x === expected.x && actual.z === expected.z, message);
}

function gitBlobIdentity(sourcePath) {
  const sourceText = execFileSync('git', ['-C', sourceRoot, 'show', `${SOURCE_COMMIT}:${sourcePath}`], {
    encoding: 'utf8',
  });
  const blob = execFileSync('git', ['-C', sourceRoot, 'rev-parse', `${SOURCE_COMMIT}:${sourcePath}`], {
    encoding: 'utf8',
  }).trim();
  return { git_blob: blob, sha256: sha256Text(sourceText) };
}

function writeOrCheck(path, content, name) {
  if (checkOnly) {
    assert(existsSync(path), `${name} is missing; run the reserved NPC placement generator`);
    assert(readFileSync(path, 'utf8') === content, `${name} is stale; run the reserved NPC placement generator`);
    return;
  }
  writeFileSync(path, content, 'utf8');
}

function zrString(value) { return JSON.stringify(value); }
function zrNumber(value) {
  assert(Number.isFinite(value), 'reserved NPC placement contains a non-finite number');
  return String(value);
}
function sha256(value) { return sha256Text(value); }
function sha256Text(value) { return createHash('sha256').update(value).digest('hex'); }
function assert(condition, message) { if (!condition) throw new Error(message); }

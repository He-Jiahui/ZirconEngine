import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const inputPath = join(projectRoot, 'contracts', 'm5_content.json');
const outputPath = join(
  projectRoot,
  'scripts',
  'woc_game',
  'src',
  'generated',
  'm5_content_catalog.zr',
);
const checkOnly = process.argv.includes('--check');

const CATEGORIES = [
  ['item', 'items'],
  ['quest', 'quests'],
  ['mob', 'mobs'],
  ['npc', 'npcs'],
  ['talent_option', 'talent_options'],
  ['ability', 'abilities'],
  ['spec', 'specs'],
];

main();

function main() {
  const document = JSON.parse(readFileSync(inputPath, 'utf8'));
  invariant(document.schema_version === 2, 'unsupported M5 content schema');
  const fingerprint = hashText(JSON.stringify({
    scenarios: document.scenarios,
    market_cut: document.market_cut,
    constants: document.constants,
    specs: document.specs,
    items: document.items,
    quests: document.quests,
    mobs: document.mobs,
    npcs: document.npcs,
    talent_options: document.talent_options,
    abilities: document.abilities,
  }));
  invariant(document.catalog_sha256 === fingerprint, 'M5 content catalog fingerprint drifted');
  validate(document);
  writeOrCheck(outputPath, render(document));
  process.stdout.write(
    `${checkOnly ? 'checked' : 'generated'} WOC M5 Zr content projection ` +
      `(${document.catalog_sha256.slice(0, 15)})\n`,
  );
}

function validate(document) {
  const expectedCounts = {
    items: 35,
    quests: 2,
    mobs: 1,
    npcs: 6,
    talent_options: 3,
    abilities: 3,
    specs: 2,
  };
  for (const [, field] of CATEGORIES) {
    invariant(document[field].length === expectedCounts[field], `M5 ${field} count drifted`);
    const ids = new Set();
    for (const entry of document[field]) {
      invariant(typeof entry.id === 'string' && entry.id.length > 0, `M5 ${field} id missing`);
      invariant(!ids.has(entry.id), `duplicate M5 ${field} id ${entry.id}`);
      invariant(entry.definition.id === entry.id, `M5 ${field} definition drifted at ${entry.id}`);
      ids.add(entry.id);
    }
  }
  invariant(document.constants.xp_for_level.length === document.constants.max_level,
    'M5 XP table length drifted');
  invariant(document.constants.bank_expansion_prices.length === 12,
    'M5 bank expansion table length drifted');
}

function render(document) {
  const lines = [
    '// Generated by examples/woc/tools/m5_content_zr_codegen.mjs.',
    `// Source ${document.source_commit}; scalar M5 content projection; do not edit.`,
    '',
    'pub catalogSha(): string {',
    `    return ${zrString(document.catalog_sha256)};`,
    '}',
    '',
    'pub count(kind: string): int {',
  ];
  for (const [kind, field] of CATEGORIES) {
    lines.push(`    if (kind == ${zrString(kind)}) { return ${document[field].length}; }`);
  }
  lines.push('    throw "unknown WOC M5 content kind";', '}', '',
    'pub indexOf(kind: string, id: string): int {');
  for (const [kind, field] of CATEGORIES) {
    lines.push(`    if (kind == ${zrString(kind)}) {`);
    document[field].forEach((entry, index) => {
      lines.push(`        if (id == ${zrString(entry.id)}) { return ${index}; }`);
    });
    lines.push('        return -1;', '    }');
  }
  lines.push('    throw "unknown WOC M5 content kind";', '}', '');
  lines.push(...renderItemIdBytes(document), '');
  renderValueFunction(lines, document, 'text', textValues, 'string', '""');
  lines.push('');
  renderValueFunction(lines, document, 'metric', metricValues, 'float', '0.0');
  lines.push('');
  renderValueFunction(lines, document, 'flag', flagValues, 'bool', 'false');
  lines.push('', ...renderItemAllowsClass(document));
  lines.push('', ...renderVendor(document), '', ...renderMobLoot(document), '',
    'pub maxLevel(): int {',
    `    return ${document.constants.max_level};`,
    '}',
    '',
    'pub prestigeXpPerRank(): int {',
    `    return ${document.constants.prestige_xp_per_rank};`,
    '}',
    '',
    'pub marketCut(): float {',
    `    return ${zrNumber(document.market_cut)};`,
    '}',
    '',
    'pub xpForLevel(level: int): int {');
  document.constants.xp_for_level.forEach((value, index) => {
    lines.push(`    if (level == ${index + 1}) { return ${value}; }`);
  });
  lines.push('    throw "unknown WOC M5 level";', '}', '',
    'pub bankExpansionCount(): int {',
    `    return ${document.constants.bank_expansion_prices.length};`,
    '}',
    '',
    'pub bankExpansionPrice(index: int): int {');
  document.constants.bank_expansion_prices.forEach((value, index) => {
    lines.push(`    if (index == ${index}) { return ${value}; }`);
  });
  lines.push('    throw "unknown WOC M5 bank expansion index";', '}', '',
    'pub abilityRankAtLevel(index: int, level: int): int {');
  document.abilities.forEach((entry, index) => {
    lines.push(`    if (index == ${index}) {`);
    lines.push(`        if (level < ${entry.definition.learnLevel}) { return 0; }`);
    for (const rank of [...(entry.definition.ranks ?? [])].reverse()) {
      lines.push(`        if (level >= ${rank.level}) { return ${rank.rank}; }`);
    }
    lines.push('        return 1;', '    }');
  });
  lines.push('    throw "unknown WOC M5 ability index";', '}');
  return `${lines.join('\n')}\n`;
}

function renderValueFunction(lines, document, name, valuesFor, returnType, fallback) {
  lines.push(`pub ${name}(kind: string, index: int, field: string): ${returnType} {`);
  for (const [kind, collection] of CATEGORIES) {
    lines.push(`    if (kind == ${zrString(kind)}) {`);
    document[collection].forEach((entry, index) => {
      lines.push(`        if (index == ${index}) {`);
      for (const [field, value] of Object.entries(valuesFor(kind, entry.definition))) {
        lines.push(`            if (field == ${zrString(field)}) { return ${renderValue(value)}; }`);
      }
      lines.push(`            return ${fallback};`, '        }');
    });
    lines.push('        throw "unknown WOC M5 content index";', '    }');
  }
  lines.push('    throw "unknown WOC M5 content kind";', '}');
}

function renderItemIdBytes(document) {
  const lines = [
    'pub itemIdUtf8Length(index: int): int {',
  ];
  document.items.forEach((entry, index) => {
    lines.push(`    if (index == ${index}) { return ${Buffer.byteLength(entry.id, 'utf8')}; }`);
  });
  lines.push('    throw "unknown WOC M5 item index";', '}', '',
    'pub itemIdUtf8Byte(index: int, byteIndex: int): uint {');
  document.items.forEach((entry, index) => {
    lines.push(`    if (index == ${index}) {`);
    for (const [byteIndex, value] of Buffer.from(entry.id, 'utf8').entries()) {
      lines.push(`        if (byteIndex == ${byteIndex}) { return <uint>${value}; }`);
    }
    lines.push('        throw "unknown WOC M5 item id byte";', '    }');
  });
  lines.push('    throw "unknown WOC M5 item index";', '}');
  return lines;
}

function textValues(kind, definition) {
  const objective = definition.objectives?.[0] ?? {};
  const byKind = {
    item: {
      ...pickText(definition, [
        'id', 'name', 'kind', 'quality', 'slot', 'armorType', 'requiredClass', 'questId',
      ]),
      weaponHand: definition.weapon?.hand ?? '',
    },
    quest: {
      ...pickText(definition, ['id', 'name', 'giverNpcId', 'turnInNpcId']),
      objectiveType: objective.type ?? '',
      objectiveItemId: objective.itemId ?? '',
      objectiveMobId: objective.targetMobId ?? '',
    },
    mob: pickText(definition, ['id', 'name', 'family']),
    npc: pickText(definition, ['id', 'name', 'title']),
    talent_option: {
      ...pickText(definition, ['id', 'name', 'description']),
      grantAbilityId: definition.effect?.grant?.ability ?? '',
    },
    ability: pickText(definition, ['id', 'name', 'class', 'school']),
    spec: pickText(definition, ['id', 'name', 'class', 'role', 'signature']),
  };
  return byKind[kind];
}

function renderItemAllowsClass(document) {
  const lines = ['pub itemAllowsClass(index: int, cls: string): bool {'];
  document.items.forEach((entry, index) => {
    const classes = entry.definition.requiredClass ?? [];
    const expression = classes.length === 0
      ? 'true'
      : classes.map((cls) => 'cls == ' + zrString(cls)).join(' || ');
    lines.push('    if (index == ' + index + ') { return ' + expression + '; }');
  });
  lines.push('    throw "unknown WOC M5 item index";', '}');
  return lines;
}

function metricValues(kind, definition) {
  const objective = definition.objectives?.[0] ?? {};
  const explicitRequiredLevel = Number.isFinite(definition.requiredLevel)
    ? Math.floor(definition.requiredLevel)
    : 0;
  const byKind = {
    item: compactNumbers({
      sellValue: definition.sellValue,
      buyValue: definition.buyValue,
      foodHp: definition.foodHp,
      drinkMana: definition.drinkMana,
      potionHp: definition.potionHp,
      weaponMin: definition.weapon?.min,
      weaponMax: definition.weapon?.max,
      weaponSpeed: definition.weapon?.speed,
      requiredLevel: explicitRequiredLevel,
      statStr: definition.stats?.str,
      statSta: definition.stats?.sta,
      statAgi: definition.stats?.agi,
      statInt: definition.stats?.int,
      statSpi: definition.stats?.spi,
      statArmor: definition.stats?.armor,
      bagSlots: definition.bagSlots,
      elixirValue: definition.elixir?.value,
      elixirDuration: definition.elixir?.duration,
    }),
    quest: compactNumbers({
      objectiveCount: objective.count,
      xpReward: definition.xpReward,
      copperReward: definition.copperReward,
    }),
    mob: compactNumbers(pick(definition, [
      'minLevel', 'maxLevel', 'hpBase', 'hpPerLevel', 'dmgBase', 'dmgPerLevel',
      'attackSpeed', 'armorPerLevel', 'moveSpeed', 'aggroRadius', 'scale',
    ])),
    npc: compactNumbers({ posX: definition.pos?.x, posZ: definition.pos?.z }),
    talent_option: compactNumbers({
      rowLevel: definition.row_level,
      bonusCharges: definition.effect?.ability?.[0]?.bonusCharges,
    }),
    ability: compactNumbers({
      learnLevel: definition.learnLevel,
      cost: definition.cost,
      castTime: definition.castTime,
      cooldown: definition.cooldown,
      range: definition.range,
      threatFlat: definition.threat?.flat,
      threatMult: definition.threat?.mult,
    }),
    spec: {},
  };
  return byKind[kind];
}

function flagValues(kind, definition) {
  const byKind = {
    item: {
      requiredLevelPresent: Number.isFinite(definition.requiredLevel),
      noDiscard: definition.noDiscard === true,
      noVendorSell: definition.noVendorSell === true,
      soulbound: definition.soulbound === true,
      weaponDagger: definition.weapon?.dagger === true,
    },
    quest: {},
    mob: {},
    npc: { banker: definition.banker === true, market: definition.market === true },
    talent_option: {},
    ability: {
      requiresTarget: definition.requiresTarget === true,
      requiresDodgeProc: definition.requiresDodgeProc === true,
    },
    spec: {},
  };
  return byKind[kind];
}

function renderVendor(document) {
  const lines = ['pub npcHasVendorStock(index: int): bool {'];
  document.npcs.forEach((entry, index) => {
    lines.push(`    if (index == ${index}) { return ${(entry.definition.vendorItems ?? []).length > 0}; }`);
  });
  lines.push('    throw "unknown WOC M5 NPC index";', '}', '',
    'pub npcSells(index: int, itemId: string): bool {');
  document.npcs.forEach((entry, index) => {
    lines.push(`    if (index == ${index}) {`);
    for (const itemId of entry.definition.vendorItems ?? []) {
      lines.push(`        if (itemId == ${zrString(itemId)}) { return true; }`);
    }
    lines.push('        return false;', '    }');
  });
  lines.push('    throw "unknown WOC M5 NPC index";', '}');
  return lines;
}

function renderMobLoot(document) {
  const lines = ['pub mobLootCount(index: int): int {'];
  document.mobs.forEach((entry, index) => {
    lines.push(`    if (index == ${index}) { return ${(entry.definition.loot ?? []).length}; }`);
  });
  lines.push('    throw "unknown WOC M5 mob index";', '}', '',
    'pub mobLootText(index: int, lootIndex: int, field: string): string {');
  document.mobs.forEach((entry, index) => {
    lines.push(`    if (index == ${index}) {`);
    (entry.definition.loot ?? []).forEach((loot, lootIndex) => {
      lines.push(`        if (lootIndex == ${lootIndex}) {`);
      if (typeof loot.itemId === 'string') {
        lines.push(`            if (field == "itemId") { return ${zrString(loot.itemId)}; }`);
      }
      lines.push('            return "";', '        }');
    });
    lines.push('        throw "unknown WOC M5 mob loot index";', '    }');
  });
  lines.push('    throw "unknown WOC M5 mob index";', '}', '',
    'pub mobLootMetric(index: int, lootIndex: int, field: string): float {');
  document.mobs.forEach((entry, index) => {
    lines.push(`    if (index == ${index}) {`);
    (entry.definition.loot ?? []).forEach((loot, lootIndex) => {
      lines.push(`        if (lootIndex == ${lootIndex}) {`);
      for (const field of ['copper', 'chance']) {
        if (typeof loot[field] === 'number') {
          lines.push(`            if (field == ${zrString(field)}) { return ${zrNumber(loot[field])}; }`);
        }
      }
      lines.push('            return 0.0;', '        }');
    });
    lines.push('        throw "unknown WOC M5 mob loot index";', '    }');
  });
  lines.push('    throw "unknown WOC M5 mob index";', '}');
  return lines;
}

function pickText(value, fields) {
  return Object.fromEntries(fields.map((field) => [field, textValue(value[field])]));
}

function textValue(value) {
  if (Array.isArray(value)) return value.join(',');
  return typeof value === 'string' ? value : '';
}

function pick(value, fields) {
  return Object.fromEntries(fields.map((field) => [field, value[field]]));
}

function compactNumbers(values) {
  return Object.fromEntries(Object.entries(values).filter(([, value]) => Number.isFinite(value)));
}

function renderValue(value) {
  if (typeof value === 'string') return zrString(value);
  if (typeof value === 'boolean') return String(value);
  return zrNumber(value);
}

function writeOrCheck(path, content) {
  if (checkOnly) {
    invariant(existsSync(path), `${path} is missing; run npm run generate:m5`);
    invariant(readFileSync(path, 'utf8') === content,
      `${path} is stale; run npm run generate:m5`);
    return;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content, 'utf8');
}

function zrString(value) {
  return JSON.stringify(value);
}

function zrNumber(value) {
  invariant(Number.isFinite(value), `non-finite Zr number ${value}`);
  return Number.isInteger(value) ? `${value}.0` : String(value);
}

function hashText(value) {
  return createHash('sha256').update(value, 'utf8').digest('hex');
}

function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

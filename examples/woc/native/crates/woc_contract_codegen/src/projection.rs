use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use thiserror::Error;

use crate::contract::{ContractError, ContractManifest};

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneratedProjections {
    pub fingerprint_hex: String,
    pub rust: String,
    pub zrvm: String,
}

#[derive(Debug, Error)]
pub enum ProjectionError {
    #[error(transparent)]
    Contract(#[from] ContractError),
    #[error("failed to read projection {path}: {source}")]
    Read {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("failed to write projection {path}: {source}")]
    Write {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("generated projection drift at {path}")]
    Drift { path: PathBuf },
}

pub fn generate_projections(
    manifest: &ContractManifest,
) -> Result<GeneratedProjections, ProjectionError> {
    manifest.validate()?;
    let fingerprint = manifest.fingerprint()?;
    let fingerprint_hex = fingerprint
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect::<String>();
    Ok(GeneratedProjections {
        rust: generate_rust(manifest, &fingerprint_hex, &fingerprint),
        zrvm: generate_zrvm(manifest, &fingerprint_hex),
        fingerprint_hex,
    })
}

pub fn verify_projection(path: impl AsRef<Path>, expected: &str) -> Result<(), ProjectionError> {
    let path = path.as_ref();
    let actual = fs::read_to_string(path).map_err(|source| ProjectionError::Read {
        path: path.to_path_buf(),
        source,
    })?;
    if actual != expected {
        return Err(ProjectionError::Drift {
            path: path.to_path_buf(),
        });
    }
    Ok(())
}

pub fn write_projection(path: impl AsRef<Path>, contents: &str) -> Result<(), ProjectionError> {
    let path = path.as_ref();
    if let Some(parent) = path.parent() {
        fs::create_dir_all(parent).map_err(|source| ProjectionError::Write {
            path: parent.to_path_buf(),
            source,
        })?;
    }
    fs::write(path, contents).map_err(|source| ProjectionError::Write {
        path: path.to_path_buf(),
        source,
    })
}

fn generate_rust(
    manifest: &ContractManifest,
    fingerprint_hex: &str,
    fingerprint: &[u8; 32],
) -> String {
    let mut output = String::new();
    writeln!(
        output,
        "// @generated by woc_contract_codegen; do not edit."
    )
    .unwrap();
    writeln!(
        output,
        "pub const CONTRACT_SCHEMA_VERSION: u16 = {};",
        manifest.schema_version
    )
    .unwrap();
    writeln!(
        output,
        "pub const PROTOCOL_VERSION: u16 = {};",
        manifest.protocol_version
    )
    .unwrap();
    writeln!(output, "pub const SCHEMA_FINGERPRINT_HEX: &str =").unwrap();
    writeln!(output, "    \"{fingerprint_hex}\";").unwrap();
    writeln!(output, "pub const SCHEMA_FINGERPRINT_BYTES: [u8; 32] = [").unwrap();
    for (index, byte) in fingerprint.iter().enumerate() {
        if index % 16 == 0 {
            output.push_str("    ");
        }
        write!(output, "0x{byte:02x},").unwrap();
        if index % 16 == 15 {
            output.push('\n');
        } else {
            output.push(' ');
        }
    }
    output.push_str("];\n\n");
    write_rust_constants(
        &mut output,
        "contract_id",
        manifest.contracts.iter().map(|item| (&item.name, item.id)),
    );
    for contract in &manifest.contracts {
        write_rust_field_constants(&mut output, contract);
    }
    for definition in &manifest.enums {
        write_rust_constants(
            &mut output,
            &format!("{}_value", snake_case(&definition.name)),
            definition
                .values
                .iter()
                .map(|value| (&value.name, value.id)),
        );
    }
    writeln!(output, "pub mod limit {{").unwrap();
    for (name, value) in &manifest.limits {
        writeln!(
            output,
            "    pub const {}: u64 = {value};",
            screaming_snake(name)
        )
        .unwrap();
    }
    output.push_str("}\n");
    output
}

fn write_rust_constants<'a>(
    output: &mut String,
    module: &str,
    values: impl IntoIterator<Item = (&'a String, u16)>,
) {
    writeln!(output, "pub mod {module} {{").unwrap();
    for (name, value) in values {
        writeln!(
            output,
            "    pub const {}: u16 = {value};",
            screaming_snake(name)
        )
        .unwrap();
    }
    output.push_str("}\n\n");
}

fn write_rust_field_constants(output: &mut String, contract: &crate::contract::ContractDefinition) {
    writeln!(output, "pub mod {}_field_id {{", snake_case(&contract.name)).unwrap();
    for field in &contract.fields {
        let name = screaming_snake(&field.name);
        writeln!(output, "    pub const {name}: u16 = {};", field.id).unwrap();
        if let Some(max_length) = field.max_length {
            writeln!(
                output,
                "    pub const {name}_MAX_LENGTH: u64 = {max_length};"
            )
            .unwrap();
        }
    }
    output.push_str("}\n\n");
}

fn generate_zrvm(manifest: &ContractManifest, fingerprint_hex: &str) -> String {
    let mut output = String::new();
    output.push_str("// @generated by woc_contract_codegen; do not edit.\n");
    write_zrvm_value(&mut output, "schemaVersion", manifest.schema_version);
    write_zrvm_value(&mut output, "protocolVersion", manifest.protocol_version);
    writeln!(
        output,
        "pub var schemaFingerprint = () => {{ return \"{fingerprint_hex}\"; }};"
    )
    .unwrap();
    for contract in &manifest.contracts {
        write_zrvm_value(
            &mut output,
            &format!("contract{}", contract.name),
            contract.id,
        );
        for field in &contract.fields {
            write_zrvm_value(
                &mut output,
                &format!("field{}{}", contract.name, upper_camel(&field.name)),
                field.id,
            );
            if let Some(max_length) = field.max_length {
                writeln!(
                    output,
                    "pub var field{}{}MaxLength = () => {{ return {max_length}; }};",
                    contract.name,
                    upper_camel(&field.name)
                )
                .unwrap();
            }
        }
    }
    for definition in &manifest.enums {
        for value in &definition.values {
            write_zrvm_value(
                &mut output,
                &format!("{}{}", lower_camel(&definition.name), value.name),
                value.id,
            );
        }
    }
    for (name, value) in &manifest.limits {
        writeln!(
            output,
            "pub var limit{} = () => {{ return {value}; }};",
            upper_camel(name)
        )
        .unwrap();
    }
    output
}

fn write_zrvm_value(output: &mut String, name: &str, value: u16) {
    writeln!(output, "pub var {name} = () => {{ return {value}; }};").unwrap();
}

fn snake_case(value: &str) -> String {
    let mut output = String::new();
    for (index, character) in value.chars().enumerate() {
        if character.is_ascii_uppercase() && index > 0 {
            output.push('_');
        }
        output.push(character.to_ascii_lowercase());
    }
    output
}

fn screaming_snake(value: &str) -> String {
    snake_case(value).to_ascii_uppercase()
}

fn upper_camel(value: &str) -> String {
    value
        .split('_')
        .filter(|segment| !segment.is_empty())
        .map(|segment| {
            let mut characters = segment.chars();
            match characters.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + characters.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn lower_camel(value: &str) -> String {
    let value = upper_camel(value);
    let mut characters = value.chars();
    match characters.next() {
        Some(first) => first.to_ascii_lowercase().to_string() + characters.as_str(),
        None => String::new(),
    }
}
